"""AID runtime for Python: the execution half of a generated application.

The AID framework generates an application from an IR that declares *what* the
app does. This package is what the generated code calls at runtime: pin a model,
run a prompt, call a tool, trace it, stay inside a budget, and prove that quality
did not regress.

Design boundaries worth stating up front, because they are deliberate:

* **Control flow is plain async Python.** There is no graph or orchestration
  engine here. A generated app is ordinary code that is easy to read and to test.
* **Pydantic AI is used only for structured output.** No other responsibility is
  delegated to it.
* **Streaming is SSE, and served end to end.** A model and its adapter that
  advertise ``Capability.STREAMING`` are served by
  :meth:`~aid_runtime.gateway.ModelGateway.stream`, which yields Server-Sent Event
  ``data`` frames with the first delta before completion. Anything not advertising
  the capability raises :class:`~aid_runtime.errors.CapabilityMismatchError`
  instead of pretending to stream.
* **One narrow adapter seam, four dialects, and a fake.** Breadth of vendor
  coverage stays a later concern; a correct seam is worth more than a wide shallow
  one. Four dialects ship: OpenAI-compatible, Anthropic Messages, Bedrock Converse,
  and Vertex AI, alongside a deterministic fake that lets the eval gate run offline.
"""

