import { afterAll, describe, expect, it } from 'vitest';

import type { Project } from './helpers.js';
import { aid, cloneExample, diagnosticsOf, project, SPEC_PATH } from './helpers.js';

const created: Project[] = [];

function example(): Project {
  const made = cloneExample();
  created.push(made);
  return made;
}

function scratch(specText?: string): Project {
  const made = project(specText);
  created.push(made);
  return made;
}

afterAll(() => {
  for (const made of created) made.close();
});

const MANIFEST = 'app/aid.manifest.json';

function codes(run: ReturnType<typeof aid>): readonly string[] {
  return diagnosticsOf(run).map((diagnostic) => diagnostic.code);
}

interface ManifestShape {
  generatedBy: { generator: string; generatorVersion: string; irVersion: string };
}

function editManifest(made: Project, edit: (manifest: ManifestShape) => void): void {
  const manifest = JSON.parse(made.read(MANIFEST)) as ManifestShape;
  edit(manifest);
  made.write(MANIFEST, JSON.stringify(manifest, null, 2));
}

describe('aid doctor', () => {
  it('reports the committed example as clean, and writes nothing to say so', () => {
    // The example is the golden tree: `aid gen` on it is byte-identical, so a doctor that
    // found anything here would be reporting its own bug, not the app's.
    const made = example();
    const before = made.snapshot();

    const run = aid(made, ['doctor']);

    expect(run.code).toBe(0);
    expect(run.stdout).toContain('ok (0 errors, 0 warnings)');
    expect(run.stdout).toContain(
      `manifest: ${MANIFEST}, generated by @aid-framework/generator-py-fastapi`,
    );
    expect(run.stdout).toContain('match the spec');
    expect(made.snapshot()).toEqual(before);

    const report = aid(made, ['doctor', '--json']).json<{
      tree: { generatedMissing: string[]; businessMissing: string[]; outdated: string[] };
    }>();
    expect(report.tree.generatedMissing).toEqual([]);
    expect(report.tree.businessMissing).toEqual([]);
    expect(report.tree.outdated).toEqual([]);
  });

  it('does not repair a broken tree, it reports it', () => {
    // Doctor shares `planRegeneration` with `aid gen --dry-run`, and the property that
    // makes it safe to run at any time is that it never reaches `regenerate`.
    const made = example();
    made.write('app/generated/agents.py', 'a hand edit\n');
    const before = made.snapshot();

    const run = aid(made, ['doctor']);

    expect(run.code).toBe(1);
    expect(made.snapshot()).toEqual(before);
  });

  it('reports a project that has never been generated as one fact, not as missing files', () => {
    const made = scratch();
    const run = aid(made, ['doctor']);

    expect(run.code).toBe(1);
    expect(run.stdout).toContain('absent, the tree has never been generated');
    expect(run.stdout).toContain('not checked');

    const json = aid(made, ['doctor', '--json']);
    expect(codes(json)).toContain('cli/manifest-missing');
    expect(json.json<{ manifest: { state: string } }>().manifest.state).toBe('absent');
  });

  it('reports a manifest it cannot read as one error, and does not guess at the tree', () => {
    // The tree may well be fine; the record of what generated it is not. Checking the
    // tree against an unreadable manifest would mean inventing the hashes it records.
    const made = example();
    made.write(MANIFEST, '{ not json');

    const run = aid(made, ['doctor']);

    expect(run.code).toBe(1);
    expect(run.stdout).toContain(`${MANIFEST}, unreadable`);
    expect(run.stdout).toContain('the manifest could not be read');
    expect(run.stdout).not.toContain('missing generated files:');
    const json = aid(made, ['doctor', '--json']);
    expect(json.json<{ manifest: { state: string } }>().manifest.state).toBe('unreadable');
  });

  it('names a missing generated file', () => {
    const made = example();
    made.remove('app/generated/agents.py');

    const run = aid(made, ['doctor']);

    expect(run.code).toBe(1);
    expect(run.stdout).toContain('missing generated files:');
    expect(run.stdout).toContain('app/generated/agents.py');
    expect(codes(aid(made, ['doctor', '--json']))).toContain('cli/files-missing');
  });

  it('names a missing business file', () => {
    // The two owners are not interchangeable: a missing generated file is a tree that
    // cannot import, a missing business file is a prompt that does not exist. Doctor
    // reports them under their own codes.
    const made = example();
    made.remove('app/business/tools/lookup_customer.py');

    const run = aid(made, ['doctor']);

    expect(run.code).toBe(1);
    expect(run.stdout).toContain('missing business files:');
    expect(run.stdout).toContain('app/business/tools/lookup_customer.py');
    expect(codes(aid(made, ['doctor', '--json']))).toContain('cli/business-missing');
  });

  it('reports a hand-edited generated file as a conflict, with the SDK code', () => {
    const made = example();
    made.write('app/generated/agents.py', 'a hand edit\n');

    const run = aid(made, ['doctor']);

    expect(run.code).toBe(1);
    expect(run.stdout).toContain('hand-edited generated files:');
    expect(run.stdout).toContain('app/generated/agents.py');
    expect(codes(aid(made, ['doctor', '--json']))).toContain('generator/generated-drift');
  });

  it('warns, and exits 0, when the spec moved on but nobody edited the tree', () => {
    // Regenerating loses nothing here, so it is not an error: the difference between
    // "run aid gen" and "resolve this by hand" is the difference between the codes.
    const made = example();
    // The output-token ceiling is embedded in `generated/gateway/models.py`, so lowering
    // it means exactly one generated file is behind the spec -- and nothing is hand-edited.
    const spec = made
      .read(SPEC_PATH)
      .replace('      maxTokens: 512\n', '      maxTokens: 400\n')
      .replace('      maxOutputTokens: 512', '      maxOutputTokens: 400');
    expect(spec).not.toBe(made.read(SPEC_PATH));
    made.setSpec(spec);

    const run = aid(made, ['doctor', '--json']);

    expect(run.code).toBe(0);
    expect(codes(run)).toContain('cli/files-outdated');
    const { outdated } = run.json<{ tree: { outdated: string[] } }>().tree;
    expect(outdated).toEqual(['app/generated/gateway/models.py']);
    expect(diagnosticsOf(run).every((diagnostic) => diagnostic.severity === 'warning')).toBe(true);
  });

  it('warns about a manifest written by another generator version', () => {
    const made = example();
    editManifest(made, (manifest) => {
      manifest.generatedBy.generatorVersion = '0.0.1';
    });

    const run = aid(made, ['doctor', '--json']);

    expect(run.code).toBe(0);
    expect(codes(run)).toContain('cli/version-mismatch');
    expect(diagnosticsOf(run).every((diagnostic) => diagnostic.severity === 'warning')).toBe(true);
  });

  it('fails when the tree belongs to a different target', () => {
    const made = example();
    editManifest(made, (manifest) => {
      manifest.generatedBy.generator = 'ts-vercel';
    });

    const run = aid(made, ['doctor', '--json']);

    expect(run.code).toBe(1);
    expect(codes(run)).toContain('cli/provenance-mismatch');
  });

  it('rejects an unknown target as a usage error, not a project judgement', () => {
    const made = example();
    const run = aid(made, ['doctor', '--target', 'nope', '--json']);
    expect(run.code).toBe(2);
    expect(codes(run)).toContain('cli/unknown-target');
  });

  it('still reports the manifest when the spec itself does not compile', () => {
    const made = example();
    made.setSpec('specVersion: "0.2"\nproject: [\n');

    const run = aid(made, ['doctor']);

    expect(run.code).toBe(1);
    expect(run.stdout).toContain('the spec did not compile');
    // The manifest is still readable, and saying so is the point of a diagnosis that
    // does not stop at the first failing check.
    expect(run.stdout).toContain(`manifest: ${MANIFEST}`);
  });
});
