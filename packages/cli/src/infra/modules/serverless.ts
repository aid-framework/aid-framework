/**
 * Provider code: the OpenTofu module a `serverless` deployment is rendered into.
 *
 * `emit.ts` deliberately holds derived *shape* only. This file is the exception the
 * design allows, and it earns it two ways: the module carries no fact the plan does not
 * already state (it loops over the tfvars rather than baking in names), and its bytes are
 * a constant, so it can be `tofu validate`d once and be right for every project. A module
 * that embedded per-service blocks would be unvalidated HCL again, one project at a time.
 *
 * What it provisions: one IAM role per service, one container-image Lambda per service,
 * and one HTTP API with a `$default` stage routing each pipeline's endpoints at its
 * service. What it refuses: a `streaming` service (HTTP API cannot stream a response
 * body; the same service runs unchanged as `serverless` on GCP, where Cloud Run streams),
 * body), a service with no image URI, and a secret with no ARN -- all as `precondition`s,
 * so the refusal arrives at `plan` with a sentence rather than as a 502 after deploy.
 *
 * Still business inputs, never derived here (design §12.2): region, account, memory,
 * timeout, tags, the image each service runs, and the ARN of each secret. The
 * `deployments[].image` registry is `ghcr.io`, which Lambda cannot pull from, so the image
 * a deployment runs is a separate, environment-specific choice.
 */

import type { DeployPlan } from '@aid-framework/ir';

import { INFRA_GENERATED_DIR } from '../paths.js';
import { GUARDRAIL_VARIABLES, guardrailLocals, guardrailResources } from './guardrails.js';
import { hcl, type ModuleFile, moduleFiles, targets } from './hcl.js';
import {
  KNOWLEDGE_BASE_VARIABLES,
  knowledgeBaseGrant,
  knowledgeBaseLocals,
} from './knowledge-base.js';

export const SERVERLESS_MODULE_DIR = `${INFRA_GENERATED_DIR}/modules/serverless`;

const VERSIONS_TF = hcl([
  '# Generated by `aid infra gen`. Do not edit: the next run refuses to overwrite a',
  '# hand-edited file, and the module carries no project-specific fact to keep.',
  'terraform {',
  '  required_version = ">= 1.6.0"',
  '',
  '  required_providers {',
  '    aws = {',
  '      source  = "hashicorp/aws"',
  '      version = "~> 5.0"',
  '    }',
  '  }',
  '}',
]);

const VARIABLES_TF = hcl([
  'variable "project" {',
  '  type = object({',
  '    name      = string',
  '    namespace = string',
  '  })',
  '}',
  '',
  'variable "services" {',
  '  description = "The plan services, verbatim. Entries not targeting serverless are ignored."',
  '  type = map(object({',
  '    target       = string',
  '    streaming    = bool',
  '    providers    = list(string)',
  '    ingest       = list(string)',
  '    secret_names = list(string)',
  '    # Every guardrail engine the spec names; `bedrock` means this build calls one.',
  '    guardrail_engines = list(string)',
  '    # Set only by a `batch` service; the other targets ignore it and the entrypoint does',
  '    # not read it, but the shared variable type must admit it.',
  '    pipeline = optional(string)',
  '    routes = list(object({',
  '      pipeline = string',
  '      method   = string',
  '      path     = string',
  '    }))',
  '    env = list(object({',
  '      name   = string',
  '      secret = bool',
  '      from   = string',
  '      value  = optional(string)',
  '    }))',
  '  }))',
  '}',
  '',
  'variable "image_uris" {',
  '  description = "Business input: the container image each serverless service runs."',
  '  type        = map(string)',
  '}',
  '',
  'variable "secret_arns" {',
  '  description = "Business input: Secrets Manager ARN per secret name, resolved at invoke time."',
  '  type        = map(string)',
  '  default     = {}',
  '}',
  '',
  'variable "sizing" {',
  '  description = "Business input: per-service memory and timeout."',
  '  type = map(object({',
  '    memory_mb       = number',
  '    timeout_seconds = number',
  '  }))',
  '  default = {}',
  '}',
  '',
  'variable "tags" {',
  '  type    = map(string)',
  '  default = {}',
  '}',
  '',
  'variable "bedrock_region" {',
  '  description = "Region for Bedrock calls. Empty means the region this stack deploys into."',
  '  type        = string',
  '  default     = ""',
  '}',
  ...GUARDRAIL_VARIABLES,
  ...KNOWLEDGE_BASE_VARIABLES,
]);

const MAIN_TF = hcl([
  'data "aws_region" "current" {}',
  '',
  'data "aws_partition" "current" {}',
  'data "aws_caller_identity" "current" {}',
  '',
  'locals {',
  '  serverless = {',
  '    for id, service in var.services : id => service',
  '    if service.target == "serverless"',
  '  }',
  '',
  '  # A service that names Bedrock calls it with the function role, so the grant below is',
  "  # the only credential it needs. `providers` is derived from the build's models, so this",
  '  # is conservative: every function in a build that mentions Bedrock gets the grant.',
  '  bedrock = {',
  '    for id, service in local.serverless : id => service',
  '    if contains(service.providers, "bedrock")',
  '  }',
  '',
  '  bedrock_region = var.bedrock_region != "" ? var.bedrock_region : data.aws_region.current.name',
  '',
  '  # Only a service with a route can be reached through the API, and a plan with no',
  '  # route needs no API at all -- so the gateway is keyed off this, not off services.',
  '  routed = {',
  '    for id, service in local.serverless : id => service',
  '    if length(service.routes) > 0',
  '  }',
  '',
  '  # One entry per (service, route), keyed the way the route key is written so the map',
  '  # key is also the Terraform address -- a diff names the route that moved.',
  '  routes = {',
  '    for pair in flatten([',
  '      for id, service in local.routed : [',
  '        for route in service.routes : { service = id, method = route.method, path = route.path }',
  '      ]',
  '    ]) : "@{pair.service} @{pair.method} @{pair.path}" => pair',
  '  }',
  '',
  '  # Lambda names allow letters, digits, hyphens and underscores, while a namespace may',
  '  # carry a dot; the replacement is what keeps `aid.test` a legal function name.',
  '  name = {',
  '    for id, service in local.serverless :',
  '    id => substr(',
  '      replace("@{var.project.namespace}-@{var.project.name}-@{id}", "/[^A-Za-z0-9-_]/", "-"),',
  '      0,',
  '      64,',
  '    )',
  '  }',
  '',
  '  # A literal env value is copied; a secret reference becomes a Lambda dynamic',
  '  # reference, so the value never enters state or a plan file.',
  '  literal_env = {',
  '    for id, service in local.serverless : id => merge(',
  '      contains(service.providers, "bedrock") ? { AWS_REGION = local.bedrock_region } : {},',
  '      {',
  '        for variable in service.env : variable.name => variable.value',
  '        if variable.secret == false && variable.value != null',
  '      },',
  '      # A provisioned guardrail is named here, so the app never learns an id by hand.',
  '      contains(keys(local.managed_guardrails), id) ? {',
  '        BEDROCK_GUARDRAIL_ID      = aws_bedrock_guardrail.managed[id].guardrail_id',
  '        BEDROCK_GUARDRAIL_VERSION = aws_bedrock_guardrail_version.managed[id].version',
  '      } : {},',
  '      local.knowledge_base_env[id],',
  '    )',
  '  }',
  '',
  '  secret_env = {',
  '    for id, service in local.serverless : id => {',
  '      for variable in service.env :',
  '      variable.name => "{{resolve:secretsmanager:@{var.secret_arns[variable.name]}:SecretString}}"',
  '      if variable.secret',
  '    }',
  '  }',
  ...guardrailLocals('serverless'),
  ...knowledgeBaseLocals('serverless'),
  '}',
  '',
  'resource "aws_iam_role" "service" {',
  '  for_each = local.serverless',
  '  name     = "@{local.name[each.key]}-role"',
  '  tags     = var.tags',
  '',
  '  assume_role_policy = jsonencode({',
  '    Version = "2012-10-17"',
  '    Statement = [{',
  '      Effect    = "Allow"',
  '      Principal = { Service = "lambda.amazonaws.com" }',
  '      Action    = "sts:AssumeRole"',
  '    }]',
  '  })',
  '}',
  '',
  'resource "aws_iam_role_policy_attachment" "logs" {',
  '  for_each   = local.serverless',
  '  role       = aws_iam_role.service[each.key].name',
  '  policy_arn = "arn:aws:iam::aws:policy/service-role/AWSLambdaBasicExecutionRole"',
  '}',
  '',
  "# Lambda resolves a dynamic secret reference with the function's own role, so a",
  '# declared secret is unusable without this. `for_each` over an empty map rather than',
  '# `count`, because a policy with no resource is invalid rather than merely empty.',
  'resource "aws_iam_role_policy" "secrets" {',
  '  for_each = length(var.secret_arns) > 0 ? local.serverless : {}',
  '  name     = "@{local.name[each.key]}-secrets"',
  '  role     = aws_iam_role.service[each.key].id',
  '',
  '  policy = jsonencode({',
  '    Version = "2012-10-17"',
  '    Statement = [{',
  '      Effect   = "Allow"',
  '      Action   = ["secretsmanager:GetSecretValue"]',
  '      Resource = values(var.secret_arns)',
  '    }]',
  '  })',
  '}',
  '',
  '# Bedrock authenticates with this role, so the function needs no API key. The stream',
  '# action is granted only to a service that streams, so the policy describes what the',
  '# spec asked for.',
  'resource "aws_iam_role_policy" "bedrock" {',
  '  for_each = local.bedrock',
  '  name     = "@{local.name[each.key]}-bedrock"',
  '  role     = aws_iam_role.service[each.key].id',
  '',
  '  policy = jsonencode({',
  '    Version = "2012-10-17"',
  '    Statement = [{',
  '      Effect = "Allow"',
  '      Action = concat(',
  '        ["bedrock:InvokeModel"],',
  '        each.value.streaming ? ["bedrock:InvokeModelWithResponseStream"] : [],',
  '      )',
  '      Resource = [',
  '        "arn:@{data.aws_partition.current.partition}:bedrock:*::foundation-model/*",',
  '        "arn:@{data.aws_partition.current.partition}:bedrock:*:@{data.aws_caller_identity.current.account_id}:inference-profile/*",',
  '      ]',
  '    }]',
  '  })',
  '}',
  ...guardrailResources('aws_iam_role.service[each.key].id'),
  ...knowledgeBaseGrant('aws_iam_role.service[each.key].id', 'serverless'),
  '',
  'resource "aws_lambda_function" "service" {',
  '  for_each = local.serverless',
  '',
  '  function_name = local.name[each.key]',
  '  role          = aws_iam_role.service[each.key].arn',
  '  package_type  = "Image"',
  '  image_uri     = var.image_uris[each.key]',
  '  tags          = var.tags',
  '',
  '  memory_size = try(var.sizing[each.key].memory_mb, 1024)',
  '  timeout     = try(var.sizing[each.key].timeout_seconds, 30)',
  '',
  '  environment {',
  '    variables = merge(local.literal_env[each.key], local.secret_env[each.key])',
  '  }',
  '',
  '  lifecycle {',
  '    precondition {',
  '      condition     = contains(keys(var.image_uris), each.key)',
  '      error_message = "No image_uris entry for \\"@{each.key}\\". Name the container image this service runs; deployments[].image is a ghcr.io registry, which Lambda cannot pull from."',
  '    }',
  '',
  '    precondition {',
  '      condition     = !each.value.streaming',
  '      error_message = "Service \\"@{each.key}\\" declares streaming, which an HTTP API cannot deliver on AWS. Serve it from a container target here, or deploy it as serverless on GCP, where Cloud Run streams."',
  '    }',
  '',
  '    precondition {',
  '      condition = alltrue([',
  '        for variable in each.value.env : contains(keys(var.secret_arns), variable.name)',
  '        if variable.secret',
  '      ])',
  '      error_message = "Service \\"@{each.key}\\" references a secret with no secret_arns entry. Add name -> ARN for every secret it declares."',
  '    }',
  '  }',
  '}',
  '',
  'resource "aws_apigatewayv2_api" "http" {',
  '  count         = length(local.routes) > 0 ? 1 : 0',
  '  name          = "@{var.project.namespace}-@{var.project.name}"',
  '  protocol_type = "HTTP"',
  '  tags          = var.tags',
  '}',
  '',
  'resource "aws_apigatewayv2_stage" "default" {',
  '  count       = length(local.routes) > 0 ? 1 : 0',
  '  api_id      = aws_apigatewayv2_api.http[0].id',
  '  name        = "$default"',
  '  auto_deploy = true',
  '  tags        = var.tags',
  '}',
  '',
  'resource "aws_apigatewayv2_integration" "service" {',
  '  for_each = local.routed',
  '',
  '  api_id                 = aws_apigatewayv2_api.http[0].id',
  '  integration_type       = "AWS_PROXY"',
  '  integration_uri        = aws_lambda_function.service[each.key].invoke_arn',
  '  payload_format_version = "2.0"',
  '}',
  '',
  'resource "aws_apigatewayv2_route" "route" {',
  '  for_each = local.routes',
  '',
  '  api_id    = aws_apigatewayv2_api.http[0].id',
  '  route_key = "@{each.value.method} @{each.value.path}"',
  '  target    = "integrations/@{aws_apigatewayv2_integration.service[each.value.service].id}"',
  '}',
  '',
  '# API Gateway cannot invoke a function without being told it may.',
  'resource "aws_lambda_permission" "api" {',
  '  for_each = local.routed',
  '',
  '  statement_id  = "apigateway"',
  '  action        = "lambda:InvokeFunction"',
  '  function_name = aws_lambda_function.service[each.key].function_name',
  '  principal     = "apigateway.amazonaws.com"',
  '  source_arn    = "@{aws_apigatewayv2_api.http[0].execution_arn}/*/*"',
  '}',
]);

const OUTPUTS_TF = hcl([
  'output "api_endpoint" {',
  '  description = "The HTTP API base URL, empty when the plan declares no routes."',
  '  value = (',
  '    length(aws_apigatewayv2_stage.default) > 0',
  '    ? aws_apigatewayv2_stage.default[0].invoke_url',
  '    : ""',
  '  )',
  '}',
  '',
  'output "function_names" {',
  '  value = { for id, function in aws_lambda_function.service : id => function.function_name }',
  '}',
  '',
  'output "function_arns" {',
  '  value = { for id, function in aws_lambda_function.service : id => function.arn }',
  '}',
]);

/**
 * The module, or nothing.
 *
 * Nothing is emitted when no deployment targets `serverless`, so a container-only project
 * gains no directory and no manifest entry -- the same rule `release.yml` follows.
 */
export function emitServerlessModule(plan: DeployPlan): ModuleFile[] {
  if (!targets(plan, 'serverless')) return [];

  return moduleFiles(SERVERLESS_MODULE_DIR, {
    versions: VERSIONS_TF,
    variables: VARIABLES_TF,
    main: MAIN_TF,
    outputs: OUTPUTS_TF,
  });
}
