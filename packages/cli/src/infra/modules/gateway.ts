/**
 * Provider code: the OpenTofu module a managed MCP gateway is rendered into.
 *
 * A gateway is a managed endpoint, not a compute resource. The platform hosts it, the
 * targets behind it are the federated tools, and a runtime reaches the whole set over MCP
 * by URL. That is the whole point of the construct: adding a tool becomes a target on a
 * gateway the app already talks to, instead of a rebuild of the image that bundles it.
 *
 * What this module deliberately does not do:
 *
 * - **Carry tool bodies.** A gateway federates tools that already exist somewhere; the
 *   spec's `tools:` section is a different thing (in-process handlers the app emits) and
 *   nothing here reads or changes it.
 * - **Omit target credentials.** Neither target kind carries a
 *   `credential_provider_configuration`, which matches the AWS CDK L2: it applies no default
 *   for `open_api_schema` or `mcp_server` and leaves the key out of the template. An OpenAPI
 *   backend that needs auth wants an API key or OAuth provider, and 0.24 has no field for
 *   one, so such an upstream is a stated limitation rather than a guessed default.
 * - **Set `ProtocolType`.** CloudFormation takes it and it is optional there, so the
 *   Terraform side sets the provider's required `protocol_type = "MCP"` (the same fact in
 *   the other vocabulary) and the CDK side leaves it at the construct default.
 *
 * Names are derived, not guessed. The platform's gateway name allows only letters, digits
 * and single hyphens and caps at 48 characters, while a spec name is snake_case; the
 * locals below are what make the two agree.
 */

import type { DeployPlan } from '@aid-framework/ir';

import { INFRA_GENERATED_DIR } from '../paths.js';
import { hcl, type ModuleFile, moduleFiles } from './hcl.js';

export const GATEWAY_MODULE_DIR = `${INFRA_GENERATED_DIR}/modules/gateway`;

/**
 * Pinned above the other AWS modules on purpose. `target_configuration.mcp.mcp_server`
 * arrived in provider 6.21.0, so a `~> 6.18` constraint would let `tofu init` select a
 * release whose schema has no `mcp_server` block and fail the plan instead of the apply.
 * `~> 6.21` still intersects every `~> 6.18` in the same root, so the two constraints
 * resolve to one provider.
 */
const VERSIONS_TF = hcl([
  '# Generated by `aid infra gen`. Do not edit: the next run refuses to overwrite a',
  '# hand-edited file, and the module carries no project-specific fact to keep.',
  'terraform {',
  '  required_version = ">= 1.6.0"',
  '',
  '  required_providers {',
  '    aws = {',
  '      source  = "hashicorp/aws"',
  '      version = "~> 6.21"',
  '    }',
  '  }',
  '}',
]);

const VARIABLES_TF = hcl([
  'variable "project" {',
  '  type = object({',
  '    name      = string',
  '    namespace = string',
  '  })',
  '}',
  '',
  'variable "gateways" {',
  '  description = "The plan gateways, verbatim. Every entry gets a gateway and its targets."',
  '  type = map(object({',
  '    description = optional(string, "")',
  "    # The variable the deployment exports this gateway's URL under. Computed by the CLI",
  '    # from the gateway id, because the runtime project reads the same spelling.',
  '    env_name = string',
  '    authorizer = object({',
  '      # `awsIam` or `jwt`. The two platform authorizers this spec can reach; `NONE` and',
  '      # `AUTHENTICATE_ONLY` are refused upstream rather than offered here.',
  '      kind          = string',
  '      discovery_url = optional(string, "")',
  '      audience      = optional(list(string), [])',
  '    })',
  '    targets = list(object({',
  '      name = string',
  '      # Optional prose on the target resource. The schema caps it at 200 characters, which',
  '      # is the same cap the API applies, so an accepted value is one the API will take.',
  '      description = optional(string, "")',
  '      # `openApiSchema` or `mcpServer`. Only one of the two blocks below is ever set;',
  "      # both live under the resource's single `mcp` configuration.",
  '      kind = string',
  '      open_api_schema = optional(object({',
  '        uri                     = optional(string, "")',
  '        bucket_owner_account_id = optional(string, "")',
  '        inline                  = optional(string, "")',
  '      }), null)',
  '      mcp_server = optional(object({',
  '        endpoint = optional(string, "")',
  '      }), null)',
  '    }))',
  '  }))',
  '  default = {}',
  '}',
  '',
  'variable "tags" {',
  '  type    = map(string)',
  '  default = {}',
  '}',
]);

const MAIN_TF = hcl([
  'data "aws_region" "current" {}',
  '',
  'locals {',
  '  # The gateway name allows letters, digits and single hyphens and caps at 48',
  '  # characters; a spec name is snake_case and a namespace may carry a dot. Collapsing',
  '  # every run of disallowed characters is what turns `support_tools` into `support-tools`',
  '  # in one pass, and the trim is what keeps a leading or trailing hyphen out.',
  '  slug = {',
  '    for id, gateway in var.gateways :',
  '    id => trim(replace(lower("@{var.project.namespace}-@{var.project.name}-@{id}"), "/[^a-z0-9]+/", "-"), "-")',
  '  }',
  '',
  '  # Truncation can expose a trailing hyphen, which the same pattern forbids, so the',
  '  # suffix is stripped after the cut rather than before it.',
  '  gateway_name = { for id, name in local.slug : id => trimsuffix(substr(name, 0, 48), "-") }',
  '',
  '  # One entry per (gateway, target) pair, keyed by both so a target name only has to be',
  '  # unique inside its own gateway and the emitted resource set does not depend on list',
  '  # order. The two names have different caps: a gateway caps at 48 characters and a',
  '  # target at 100, which is why the target name is built from the derived gateway name',
  '  # and capped again rather than reusing the gateway slug uncut.',
  '  targets = merge([',
  '    for id, gateway in var.gateways : {',
  '      for target in gateway.targets :',
  '      "@{id}/@{target.name}" => merge(target, { gateway = id })',
  '    }',
  '  ]...)',
  '',
  '  target_name = {',
  '    for key, target in local.targets :',
  '    key => trimsuffix(substr(trim(replace(lower("@{local.gateway_name[target.gateway]}-@{target.name}"), "/[^a-z0-9]+/", "-"), "-"), 0, 100), "-")',
  '  }',
  '}',
  '',
  '# ---------------------------------------------------------------------------- iam',
  '',
  '# The gateway assumes this role to reach the targets behind it. The principal is the',
  '# AgentCore service, which is the same one an agent runtime assumes.',
  'resource "aws_iam_role" "gateway" {',
  '  for_each = var.gateways',
  '',
  '  name = substr("@{local.gateway_name[each.key]}-role", 0, 64)',
  '  tags = var.tags',
  '',
  '  assume_role_policy = jsonencode({',
  '    Version = "2012-10-17"',
  '    Statement = [{',
  '      Effect    = "Allow"',
  '      Principal = { Service = "bedrock-agentcore.amazonaws.com" }',
  '      Action    = "sts:AssumeRole"',
  '    }]',
  '  })',
  '}',
  '',
  '# ------------------------------------------------------------------------ gateway',
  '',
  'resource "aws_bedrockagentcore_gateway" "this" {',
  '  for_each = var.gateways',
  '',
  '  name        = local.gateway_name[each.key]',
  '  description = each.value.description != "" ? each.value.description : null',
  '  role_arn    = aws_iam_role.gateway[each.key].arn',
  '',
  '  # The two platform authorizers this spec can reach. `NONE` is refused upstream because',
  '  # it publishes an unauthenticated endpoint, and `AUTHENTICATE_ONLY` authorizes nothing.',
  '  authorizer_type = each.value.authorizer.kind == "jwt" ? "CUSTOM_JWT" : "AWS_IAM"',
  '',
  '  # Required by the provider, and a constant rather than a spec field: an AgentCore',
  '  # gateway speaks MCP to its caller, which is the only protocol this layer federates.',
  '  protocol_type = "MCP"',
  '',
  '  tags = var.tags',
  '',
  "  # A JWT gateway validates the caller's token against the issuer it names. Without one",
  '  # the block is omitted rather than rendered empty: `discovery_url` is required inside it.',
  '  dynamic "authorizer_configuration" {',
  '    for_each = each.value.authorizer.kind == "jwt" ? [each.value.authorizer] : []',
  '    content {',
  '      custom_jwt_authorizer {',
  '        discovery_url    = authorizer_configuration.value.discovery_url',
  '        allowed_audience = authorizer_configuration.value.audience',
  '      }',
  '    }',
  '  }',
  '}',
  '',
  '# ------------------------------------------------------------------------ targets',
  '',
  'resource "aws_bedrockagentcore_gateway_target" "this" {',
  '  for_each = local.targets',
  '',
  '  name = local.target_name[each.key]',
  '',
  '  # The gateway identifier, not the ARN: the API addresses a target through its gateway.',
  '  # Reading it off the gateway resource is also what orders the two.',
  '  gateway_identifier = aws_bedrockagentcore_gateway.this[each.value.gateway].gateway_id',
  '',
  '  description = each.value.description != "" ? each.value.description : null',
  '',
  '  # No `credential_provider_configuration` for either target kind. That is deliberate and',
  '  # matches the AWS CDK L2, which applies no default for `open_api_schema` or `mcp_server`',
  '  # and omits the key from the synthesized template. The gap it leaves: an OpenAPI backend',
  '  # that *does* need auth wants an API key or OAuth provider, which 0.24 has no field for,',
  '  # so such an upstream is a documented limitation rather than a silent default.',
  '',
  '  # All target kinds live under `mcp`. The resource has no top-level `open_api_schema`',
  '  # and no sibling `api` block: a schema-backed target is one MCP target whose',
  '  # configuration happens to be a document.',
  '  target_configuration {',
  '    mcp {',
  '      dynamic "mcp_server" {',
  '        for_each = each.value.kind == "mcpServer" ? [each.value.mcp_server] : []',
  '        content {',
  '          endpoint = mcp_server.value.endpoint',
  '        }',
  '      }',
  '',
  '      dynamic "open_api_schema" {',
  '        for_each = each.value.kind == "openApiSchema" ? [each.value.open_api_schema] : []',
  '        content {',
  '          # Exactly one of the two, which is what `open_api_schema` documents and what the',
  '          # spec already made exclusive. An inline document travels in the plan; a uri is',
  '          # read from S3 at apply time, with the owner id only when the bucket is elsewhere.',
  '          dynamic "inline_payload" {',
  '            for_each = open_api_schema.value.inline != "" ? [open_api_schema.value.inline] : []',
  '            content {',
  '              payload = inline_payload.value',
  '            }',
  '          }',
  '',
  '          dynamic "s3" {',
  '            for_each = open_api_schema.value.inline == "" ? [open_api_schema.value.uri] : []',
  '            content {',
  '              uri                     = s3.value',
  '              bucket_owner_account_id = open_api_schema.value.bucket_owner_account_id != "" ? open_api_schema.value.bucket_owner_account_id : null',
  '            }',
  '          }',
  '        }',
  '      }',
  '    }',
  '  }',
  '}',
]);

const OUTPUTS_TF = hcl([
  '# The one output the env root wires into the runtime module: the plan entries with the',
  '# platform-assigned URL and ARN filled in. A URL only exists after the gateway does, so a',
  '# `tofu plan` before the first apply hands the runtime an empty map and no environment',
  '# variable -- the same shape a knowledge base uses.',
  'output "gateways" {',
  '  description = "Gateway id -> {arn, url, env_name}. Empty until the gateway exists."',
  '  value = {',
  '    for id, gateway in aws_bedrockagentcore_gateway.this : id => {',
  '      arn      = gateway.gateway_arn',
  '      url      = gateway.gateway_url',
  '      env_name = var.gateways[id].env_name',
  '    }',
  '  }',
  '}',
  '',
  'output "gateway_urls" {',
  '  description = "Gateway id -> the MCP endpoint a runtime connects to."',
  '  value       = { for id, gateway in aws_bedrockagentcore_gateway.this : id => gateway.gateway_url }',
  '}',
  '',
  'output "gateway_arns" {',
  '  description = "Gateway id -> ARN, for granting a runtime invoke on exactly these gateways."',
  '  value       = { for id, gateway in aws_bedrockagentcore_gateway.this : id => gateway.gateway_arn }',
  '}',
  '',
  'output "gateway_identifiers" {',
  '  description = "Gateway id -> the identifier the API assigned, which a target names."',
  '  value       = { for id, gateway in aws_bedrockagentcore_gateway.this : id => gateway.gateway_id }',
  '}',
  '',
  'output "target_ids" {',
  '  description = "`gateway/target` -> the target id the platform assigned."',
  '  value       = { for key, target in aws_bedrockagentcore_gateway_target.this : key => target.target_id }',
  '}',
]);

/**
 * The module, or nothing.
 *
 * Nothing is emitted when the plan declares no gateway, so a project without one is handed
 * no variables it would never set -- which keeps every other module's bytes constant and
 * `tofu validate` meaningful for every project.
 */
export function emitGatewayModule(plan: DeployPlan): ModuleFile[] {
  if (plan.gateways.length === 0) return [];
  return moduleFiles(GATEWAY_MODULE_DIR, {
    versions: VERSIONS_TF,
    variables: VARIABLES_TF,
    main: MAIN_TF,
    outputs: OUTPUTS_TF,
  });
}

/**
 * The input every AWS agent-runtime module declares so it can reach a gateway.
 *
 * The URL is assigned at apply time and cannot appear in the plan, so the module reads
 * this map instead of the tfvars entry verbatim: the env root merges what the gateway
 * module returned into what the plan spelled.
 */
export const GATEWAY_VARIABLES = [
  '',
  'variable "gateways" {',
  '  description = "Gateways this module may reach, with the URL and ARN the env root resolved."',
  '  type = map(object({',
  '    # Empty until the gateway exists. The environment and the grant skip it while it is.',
  '    arn = optional(string, "")',
  '    url = optional(string, "")',
  '    # The variable the runtime reads the URL from. Computed by the CLI, not here.',
  '    env_name = string',
  '  }))',
  '  default = {}',
  '}',
];

/**
 * The locals a runtime module adds beside its own.
 *
 * `gateway_arns` is separated out because a policy whose `Resource` is `[""]` is invalid
 * rather than merely empty -- the same reason `knowledge_base_arns` is.
 */
export function gatewayLocals(servicesLocal: string): string[] {
  return [
    '',
    '  # Only the gateways that exist. `tofu plan` before the first apply sees none, and',
    '  # emitting a policy with an empty resource would fail the plan rather than skip it.',
    '  gateway_arns = [for gateway in values(var.gateways) : gateway.arn if gateway.arn != ""]',
    '',
    '  # Exported only to a service that names the gateway, and only once it has a URL: a',
    '  # missing variable would read as an empty endpoint, which an MCP client cannot dial.',
    `  gateway_env = {`,
    `    for id, service in local.${servicesLocal} : id => {`,
    '      for gateway_id, gateway in var.gateways :',
    '      gateway.env_name => gateway.url',
    '      if gateway.url != "" && try(service.runtime.gateway, "") == gateway_id',
    '    }',
    '  }',
  ];
}

/**
 * The invoke grant.
 *
 * `servicesLocal` selects the per-service spelling (`for_each`, one policy per runtime
 * role). The batch module has one task role for every job, so it passes no local and gets
 * the single-role spelling instead.
 */
export function gatewayGrant(roleRef: string, servicesLocal?: string): string[] {
  const lifecycle =
    servicesLocal === undefined
      ? ['  count = length(local.gateway_arns) > 0 ? 1 : 0', `  role  = ${roleRef}`]
      : [
          `  for_each = length(local.gateway_arns) > 0 ? local.${servicesLocal} : {}`,
          `  role     = ${roleRef}`,
        ];
  return [
    '',
    '# Invoke is the only call the app makes on a gateway: the gateway itself reaches the',
    '# targets, so neither their addresses nor their credentials ever reach this role.',
    'resource "aws_iam_role_policy" "gateway" {',
    ...lifecycle,
    '  name = "@{substr(replace("@{var.project.namespace}-@{var.project.name}", "/[^A-Za-z0-9-_]/", "-"), 0, 40)}-gateway-invoke"',
    '',
    '  policy = jsonencode({',
    '    Version = "2012-10-17"',
    '    Statement = [{',
    '      Effect   = "Allow"',
    '      Action   = ["bedrock-agentcore:InvokeGateway"]',
    '      Resource = local.gateway_arns',
    '    }]',
    '  })',
    '}',
  ];
}
