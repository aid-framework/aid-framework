/**
 * Provider code: the Model Armor template a `model-armor` guardrail owns.
 *
 * A standalone module rather than a fragment beside the compute, because the template is
 * one resource per *service* while every compute module would otherwise create it: the
 * same tfvar reaches `cloudrun`, `cloudrunjob` and `agent-runtime`, and a fragment in each
 * would produce three templates for one guardrail.
 *
 * What it deliberately does not do:
 *
 * - **Own the policy vocabulary.** The tfvars carry `SEXUALLY_EXPLICIT` and
 *   `MEDIUM_AND_ABOVE`; the spec says `sexual` and `medium-and-above`. `emit.ts` maps
 *   once, so this file reads like the policy the author wrote.
 * - **Name the template.** The env root passes this module's `templates` output to the
 *   compute modules, which export it as `MODEL_ARMOR_TEMPLATE`. HCL is not asked to
 *   compose `projects/<project>/locations/<region>/templates/<id>` and then have the
 *   runtime re-parse it.
 * - **Configure the parts that name other resources.** DLP inspect/deidentify templates
 *   (`sdp_settings.advanced_config`) and custom filter rules
 *   (`filter_rule_settings`) point at resources this deployment does not create, so they
 *   are operator inputs and the spec has no field for them.
 */

import type { DeployPlan } from '@aid-framework/ir';

import { INFRA_GENERATED_DIR } from '../paths.js';
import { hcl, type ModuleFile, moduleFiles } from './hcl.js';

export const MODEL_ARMOR_MODULE_DIR = `${INFRA_GENERATED_DIR}/modules/model-armor`;

const VERSIONS_TF = hcl([
  '# Generated by `aid infra gen`. Do not edit: the next run refuses to overwrite a',
  '# hand-edited file, and the module carries no project-specific fact to keep.',
  'terraform {',
  '  required_version = ">= 1.6.0"',
  '',
  '  required_providers {',
  '    google = {',
  '      source = "hashicorp/google"',
  '      # `google_model_armor_template` first ships in 8.4.0, which is also the floor',
  '      # the knowledge-base module sets: one env root has one version per provider.',
  '      version = "~> 8.4"',
  '    }',
  '  }',
  '}',
]);

const VARIABLES_TF = hcl([
  'variable "project" {',
  '  type = object({',
  '    name      = string',
  '    namespace = string',
  '  })',
  '}',
  '',
  'variable "project_id" {',
  '  description = "The project the template is created in."',
  '  type        = string',
  '}',
  '',
  'variable "region" {',
  '  description = "The location the template lives in, and therefore the endpoint the runtime calls."',
  '  type        = string',
  '}',
  '',
  'variable "model_armor_templates" {',
  '  description = "Templates to provision, keyed by service id. Empty means no policy reached the plan."',
  '  type = map(object({',
  '    rai = optional(list(object({ type = string, confidence = string })), [])',
  '    # Absent means the spec said nothing about prompt injection, which is not the same',
  '    # as `false` on the flags below: `false` writes an explicit DISABLED.',
  '    prompt_injection = optional(object({ confidence = string }))',
  '    malicious_uri    = optional(bool)',
  '    sensitive_data   = optional(bool)',
  '  }))',
  '  default = {}',
  '}',
]);

const MAIN_TF = hcl([
  'locals {',
  '  # A template id is lowercase letters, digits and hyphens, starts with a letter, and',
  '  # caps at 63 characters. A namespace may carry a dot and truncation can leave a',
  '  # trailing hyphen, so both are cleared; the precondition below refuses anything left',
  '  # that still cannot name a template.',
  '  template_id = {',
  '    for id, template in var.model_armor_templates :',
  '    id => replace(',
  '      substr(',
  '        replace(lower("@{var.project.namespace}-@{var.project.name}-@{id}"), "/[^a-z0-9-]/", "-"),',
  '        0,',
  '        63,',
  '      ),',
  '      "/-+$/",',
  '      "",',
  '    )',
  '  }',
  '}',
  '',
  'resource "google_model_armor_template" "this" {',
  '  for_each = var.model_armor_templates',
  '',
  '  project     = var.project_id',
  '  location    = var.region',
  '  template_id = local.template_id[each.key]',
  '',
  '  filter_config {',
  '    dynamic "rai_settings" {',
  '      for_each = length(each.value.rai) > 0 ? [1] : []',
  '      content {',
  '        dynamic "rai_filters" {',
  '          for_each = each.value.rai',
  '          content {',
  '            filter_type      = rai_filters.value.type',
  '            confidence_level = rai_filters.value.confidence',
  '          }',
  '        }',
  '      }',
  '    }',
  '',
  '    # A confidence is present exactly when the spec named one, so its absence is what',
  '    # leaves the filter out rather than guessing a threshold the author did not write.',
  '    dynamic "pi_and_jailbreak_filter_settings" {',
  '      for_each = each.value.prompt_injection == null ? [] : [each.value.prompt_injection]',
  '      content {',
  '        filter_enforcement = "ENABLED"',
  '        confidence_level   = pi_and_jailbreak_filter_settings.value.confidence',
  '      }',
  '    }',
  '',
  '    # `false` is meaningful here: it writes DISABLED, which pins the filter off even if',
  '    # the API default for a new template later changes. Absence leaves the default.',
  '    dynamic "malicious_uri_filter_settings" {',
  '      for_each = each.value.malicious_uri == null ? [] : [each.value.malicious_uri]',
  '      content {',
  '        filter_enforcement = malicious_uri_filter_settings.value ? "ENABLED" : "DISABLED"',
  '      }',
  '    }',
  '',
  '    dynamic "sdp_settings" {',
  '      for_each = each.value.sensitive_data == null ? [] : [each.value.sensitive_data]',
  '      content {',
  '        # The basic config is the PII detector Model Armor owns; `advanced_config`',
  '        # would name a DLP inspect template this deployment does not create.',
  '        basic_config {',
  '          filter_enforcement = sdp_settings.value ? "ENABLED" : "DISABLED"',
  '        }',
  '      }',
  '    }',
  '  }',
  '',
  '  # Delete protection at the API level, beside `prevent_destroy`: every running service',
  '  # names this template, so a destroy would break them without changing a spec.',
  '  deletion_policy = "PREVENT"',
  '',
  '  lifecycle {',
  '    prevent_destroy = true',
  '',
  '    precondition {',
  '      condition     = can(regex("^[a-z]([a-z0-9-]{0,61}[a-z0-9])?$", local.template_id[each.key]))',
  '      error_message = "Template id \\"@{local.template_id[each.key]}\\" for service \\"@{each.key}\\" cannot name a Model Armor template: it must start with a lowercase letter and contain only lowercase letters, digits and hyphens. Shorten or rename the project namespace."',
  '    }',
  '  }',
  '}',
]);

const OUTPUTS_TF = hcl([
  '# The one output the env root wires into the compute modules: the resource name, which',
  '# is exactly what `MODEL_ARMOR_TEMPLATE` must hold. Nothing composes it by hand, so the',
  '# runtime never re-parses a name this configuration invented.',
  'output "templates" {',
  '  description = "Service id -> the template resource name."',
  '  value       = { for id, template in google_model_armor_template.this : id => template.name }',
  '}',
]);

/**
 * The input every GCP compute module declares so it can export the template name.
 *
 * A `map(string)` rather than a map of objects because the env root passes the
 * `templates` output straight through: the name is the only fact a service needs, and an
 * empty string means the resource does not exist yet. The environment skips it while it
 * is empty: the runtime raises a named error for a missing template, while an empty
 * string would read as a malformed name.
 */
export const MODEL_ARMOR_VARIABLES = [
  '',
  'variable "model_armor_templates" {',
  '  description = "Template resource names this module may export, keyed by service id."',
  '  type        = map(string)',
  '  default     = {}',
  '}',
];

/** The local a GCP compute module adds beside its own. */
export function modelArmorLocals(): string[] {
  return [
    '',
    '  # The template name the runtime reads. Exported only once the resource exists.',
    '  model_armor_env = {',
    '    for id, name in var.model_armor_templates : id => {',
    '      MODEL_ARMOR_TEMPLATE = name',
    '    }',
    '    if name != ""',
    '  }',
  ];
}

/**
 * The module, or nothing.
 *
 * Nothing is emitted when no guardrail owns a policy, so a project that only names an
 * operator-created template is handed no variables it would never set.
 */
export function emitModelArmorModule(plan: DeployPlan): ModuleFile[] {
  const ownsOne = plan.services.some(
    (service) => service.managedGuardrail?.engine === 'model-armor',
  );
  if (!ownsOne) return [];
  return moduleFiles(MODEL_ARMOR_MODULE_DIR, {
    versions: VERSIONS_TF,
    variables: VARIABLES_TF,
    main: MAIN_TF,
    outputs: OUTPUTS_TF,
  });
}
