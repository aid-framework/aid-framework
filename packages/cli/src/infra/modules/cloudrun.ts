/**
 * Provider code: the OpenTofu module a `container` deployment is rendered into when the
 * target cloud is GCP. It is the Cloud Run counterpart of `container.ts`, which emits ECS.
 *
 * Same bargain as every generated module: it carries no fact the plan does not already
 * state (it loops over the tfvars rather than baking in names), and its bytes are a
 * constant, so `tofu validate` proves it once and it is right for every project. A module
 * with per-service blocks would be unvalidated HCL again, one project at a time.
 *
 * What it provisions: a service account per service, one Cloud Run v2 service per service
 * (the generated image already listens on `$PORT`, which Cloud Run sets), a Secret Manager
 * accessor binding for each secret the service names, public invoker access when asked
 * for, and one Artifact Registry repository for the images. What it refuses: a service
 * with no image URI, a secret with no Secret Manager id, and a name that Cloud Run cannot
 * route -- all as `precondition`s, so the refusal arrives at `plan` with a sentence rather
 * than as an image pull error after deploy.
 *
 * What it does *not* refuse: a `streaming` service. Cloud Run forwards a streamed response
 * body, unlike API Gateway, so the same service that needs the container target on AWS
 * works here with no change.
 *
 * Still business inputs, never derived here (design §12.2): the project and region the
 * provider authenticates as, each service's image, memory, CPU, instance bounds,
 * concurrency, tags, and the id of each secret. Cloud Run needs no VPC, subnet or
 * certificate to answer HTTPS, so unlike the ECS module there is nothing else to supply.
 */

import type { DeployPlan } from '@aid-framework/ir';

import { INFRA_GENERATED_DIR } from '../paths.js';
import { hcl, type ModuleFile, moduleFiles, targets } from './hcl.js';

export const CLOUDRUN_MODULE_DIR = `${INFRA_GENERATED_DIR}/modules/cloudrun`;

const VERSIONS_TF = hcl([
  '# Generated by `aid infra gen`. Do not edit: the next run refuses to overwrite a',
  '# hand-edited file, and the module carries no project-specific fact to keep.',
  'terraform {',
  '  required_version = ">= 1.6.0"',
  '',
  '  required_providers {',
  '    google = {',
  '      source  = "hashicorp/google"',
  '      version = "~> 6.0"',
  '    }',
  '  }',
  '}',
]);

const VARIABLES_TF = hcl([
  'variable "project" {',
  '  type = object({',
  '    name      = string',
  '    namespace = string',
  '  })',
  '}',
  '',
  'variable "services" {',
  '  description = "The plan services, verbatim. Entries not targeting container are ignored."',
  '  type = map(object({',
  '    target       = string',
  '    streaming    = bool',
  '    providers    = list(string)',
  '    ingest       = list(string)',
  '    secret_names = list(string)',
  '    # Set only by a `batch` service; the other targets ignore it and the entrypoint does',
  '    # not read it, but the shared variable type must admit it.',
  '    pipeline = optional(string)',
  '    routes = list(object({',
  '      pipeline = string',
  '      method   = string',
  '      path     = string',
  '    }))',
  '    env = list(object({',
  '      name   = string',
  '      secret = bool',
  '      from   = string',
  '      value  = optional(string)',
  '    }))',
  '  }))',
  '}',
  '',
  'variable "image_uris" {',
  '  description = "Business input: the container image each service runs."',
  '  type        = map(string)',
  '}',
  '',
  'variable "secret_ids" {',
  '  description = "Business input: Secret Manager secret id per secret name."',
  '  type        = map(string)',
  '  default     = {}',
  '}',
  '',
  'variable "cloudrun_sizing" {',
  '  description = "Business input: per-service CPU, memory, instance bounds and concurrency."',
  '  type = map(object({',
  '    cpu           = optional(string)',
  '    memory_mb     = optional(number)',
  '    min_instances = optional(number)',
  '    max_instances = optional(number)',
  '    concurrency   = optional(number)',
  '  }))',
  '  default = {}',
  '}',
  '',
  'variable "region" {',
  '  description = "The region every resource is created in. A business input, not derived."',
  '  type        = string',
  '}',
  '',
  'variable "allow_unauthenticated" {',
  '  description = "Whether the internet may invoke the services without a Google identity."',
  '  type        = bool',
  '  default     = true',
  '}',
  '',
  'variable "deletion_protection" {',
  '  description = "Leave on for anything real: destroying a protected service is refused."',
  '  type        = bool',
  '  default     = true',
  '}',
  '',
  'variable "tags" {',
  '  type    = map(string)',
  '  default = {}',
  '}',
]);

const MAIN_TF = hcl([
  'locals {',
  '  container = {',
  '    for id, service in var.services : id => service',
  '    if service.target == "container"',
  '  }',
  '',
  '  # Cloud Run names allow lowercase letters, digits and hyphens only, are at most 63',
  '  # characters, and become the URL path -- while a namespace may carry a dot',
  '  # (`aid.test`), and a trailing hyphen after truncation is not legal. Both are cleared',
  '  # here; a name that still cannot start a request is refused by the precondition below.',
  '  name = {',
  '    for id, service in local.container :',
  '    id => substr(',
  '      replace(',
  '        replace(lower("@{var.project.namespace}-@{var.project.name}-@{id}"), "/[^a-z0-9-]/", "-"),',
  '        "/-+$/",',
  '        "",',
  '      ),',
  '      0,',
  '      63,',
  '    )',
  '  }',
  '',
  '  # Service account ids are 6-30 characters and must start with a letter, so the same',
  '  # name with a fixed prefix keeps even a one-character project legal.',
  '  account_id = {',
  '    for id, service in local.container :',
  '    id => substr(',
  '      replace(',
  '        replace(lower("aid-@{var.project.namespace}-@{var.project.name}-@{id}"), "/[^a-z0-9-]/", "-"),',
  '        "/-+$/",',
  '        "",',
  '      ),',
  '      0,',
  '      30,',
  '    )',
  '  }',
  '',
  '  # Repository id: lowercase letters, digits and hyphens, 4-63 characters, so the',
  '  # namespace and project name are enough without the service id.',
  '  repository_id = replace(',
  '    replace(lower("@{var.project.namespace}-@{var.project.name}"), "/[^a-z0-9-]/", "-"),',
  '    "/-+$/",',
  '    "",',
  '  )',
  '',
  '  # One binding per (service, secret). Keyed by both because two services may read the',
  '  # same secret and each needs its own grant for its own identity.',
  '  secret_env = {',
  '    for pair in flatten([',
  '      for id, service in local.container : [',
  '        for variable in service.env : { service = id, name = variable.name }',
  '        if variable.secret',
  '      ]',
  '    ]) : "@{pair.service}/@{pair.name}" => pair',
  '  }',
  '}',
  '',
  'resource "google_service_account" "service" {',
  '  for_each     = local.container',
  '  account_id   = local.account_id[each.key]',
  '  display_name = "@{var.project.namespace}-@{var.project.name}-@{each.key}"',
  '}',
  '',
  'resource "google_cloud_run_v2_service" "service" {',
  '  for_each = local.container',
  '',
  '  name                = local.name[each.key]',
  '  location            = var.region',
  '  labels              = var.tags',
  '  deletion_protection = var.deletion_protection',
  '',
  '  template {',
  '    service_account = google_service_account.service[each.key].email',
  '',
  '    # Cloud Run defaults to 80 concurrent requests per instance, which suits an ASGI',
  '    # app that awaits models; lower it for a service whose memory grows per request.',
  '    max_instance_request_concurrency = coalesce(',
  '      try(var.cloudrun_sizing[each.key].concurrency, null),',
  '      80,',
  '    )',
  '',
  '    scaling {',
  '      min_instance_count = coalesce(try(var.cloudrun_sizing[each.key].min_instances, null), 0)',
  '      max_instance_count = coalesce(try(var.cloudrun_sizing[each.key].max_instances, null), 10)',
  '    }',
  '',
  '    containers {',
  '      # `lookup` rather than an index: a missing entry is a business input still to',
  '      # supply, and the precondition below should say so instead of an index error.',
  '      image = lookup(var.image_uris, each.key, "")',
  '',
  '      # The generated Dockerfile reads `$PORT` and defaults it to 8080, which is also',
  '      # the port Cloud Run sends traffic to.',
  '      ports {',
  '        container_port = 8080',
  '      }',
  '',
  '      resources {',
  '        limits = {',
  '          cpu    = coalesce(try(var.cloudrun_sizing[each.key].cpu, null), "1")',
  '          memory = "@{coalesce(try(var.cloudrun_sizing[each.key].memory_mb, null), 512)}Mi"',
  '        }',
  '      }',
  '',
  '      dynamic "env" {',
  '        for_each = {',
  '          for variable in each.value.env : variable.name => variable',
  '          if variable.secret == false && variable.value != null',
  '        }',
  '        content {',
  '          name  = env.value.name',
  '          value = env.value.value',
  '        }',
  '      }',
  '',
  '      # A secret is a reference, not a value: the image reads it from the environment,',
  '      # and the value never enters state or a plan file.',
  '      dynamic "env" {',
  '        for_each = {',
  '          for variable in each.value.env : variable.name => variable',
  '          if variable.secret',
  '        }',
  '        content {',
  '          name = env.value.name',
  '          value_source {',
  '            secret_key_ref {',
  '              secret  = lookup(var.secret_ids, env.value.name, "")',
  '              version = "latest"',
  '            }',
  '          }',
  '        }',
  '      }',
  '    }',
  '  }',
  '',
  '  lifecycle {',
  '    precondition {',
  '      condition     = contains(keys(var.image_uris), each.key)',
  '      error_message = "No image_uris entry for \\"@{each.key}\\". Name the container image this service runs."',
  '    }',
  '',
  '    precondition {',
  '      condition = alltrue([',
  '        for variable in each.value.env : contains(keys(var.secret_ids), variable.name)',
  '        if variable.secret',
  '      ])',
  '      error_message = "Service \\"@{each.key}\\" references a secret with no secret_ids entry. Add name -> Secret Manager secret id for every secret it declares."',
  '    }',
  '',
  '    precondition {',
  '      condition     = can(regex("^[a-z][a-z0-9-]*$", local.name[each.key]))',
  '      error_message = "Service name \\"@{local.name[each.key]}\\" cannot be a Cloud Run name: it must start with a lowercase letter. Shorten or rename the project namespace."',
  '    }',
  '  }',
  '}',
  '',
  '# Without this binding the service account cannot read a secret, and the image fails on',
  '# its first model call rather than at plan time. `for_each` over an empty map rather than',
  '# `count`, because a binding with no secret id is invalid rather than merely empty.',
  'resource "google_secret_manager_secret_iam_member" "accessor" {',
  '  for_each = length(var.secret_ids) > 0 ? local.secret_env : {}',
  '',
  '  secret_id = lookup(var.secret_ids, each.value.name, each.value.name)',
  '  role      = "roles/secretmanager.secretAccessor"',
  '  member    = "serviceAccount:@{google_service_account.service[each.value.service].email}"',
  '}',
  '',
  '# Cloud Run authenticates every request by default. A model gateway is a public URL, so',
  '# the operator asks for the allUsers binding explicitly instead of getting it silently.',
  'resource "google_cloud_run_v2_service_iam_member" "invoker" {',
  '  for_each = var.allow_unauthenticated ? local.container : {}',
  '',
  '  name     = google_cloud_run_v2_service.service[each.key].name',
  '  location = google_cloud_run_v2_service.service[each.key].location',
  '  role     = "roles/run.invoker"',
  '  member   = "allUsers"',
  '}',
  '',
  '# The registry the images are pushed to. It is created once per project, not per',
  '# service, and only when there is a service to run.',
  'resource "google_artifact_registry_repository" "images" {',
  '  for_each = length(local.container) > 0 ? { images = true } : {}',
  '',
  '  location      = var.region',
  '  repository_id = substr(local.repository_id, 0, 63)',
  '  format        = "DOCKER"',
  '  labels        = var.tags',
  '}',
]);

const OUTPUTS_TF = hcl([
  'output "service_urls" {',
  '  description = "Service id -> the HTTPS URL Cloud Run answers on."',
  '  value       = { for id, service in google_cloud_run_v2_service.service : id => service.uri }',
  '}',
  '',
  'output "service_names" {',
  '  value = { for id, service in google_cloud_run_v2_service.service : id => service.name }',
  '}',
  '',
  'output "service_accounts" {',
  '  value = { for id, account in google_service_account.service : id => account.email }',
  '}',
  '',
  'output "repository_id" {',
  '  description = "The Artifact Registry repository images are pushed to, empty when none exists."',
  '  value = (',
  '    length(google_artifact_registry_repository.images) > 0',
  '    ? values(google_artifact_registry_repository.images)[0].repository_id',
  '    : ""',
  '  )',
  '}',
]);

/**
 * The module, or nothing.
 *
 * Nothing is emitted when no deployment targets `container`, so a plan with no service to
 * run gains no directory and no manifest entry -- the same rule every other module follows.
 */
export function emitCloudRunModule(plan: DeployPlan): ModuleFile[] {
  if (!targets(plan, 'container')) return [];

  return moduleFiles(CLOUDRUN_MODULE_DIR, {
    versions: VERSIONS_TF,
    variables: VARIABLES_TF,
    main: MAIN_TF,
    outputs: OUTPUTS_TF,
  });
}
