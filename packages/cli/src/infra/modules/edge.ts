/**
 * The module, or nothing.
 *
 * Nothing is emitted when no deployment targets `edge`, so a container-only project gains
 * no directory and no manifest entry -- the same rule every other module follows.
 */
export function emitEdgeModule(plan: DeployPlan): ModuleFile[] {
  if (!targets(plan, 'edge')) return [];

  return moduleFiles(EDGE_MODULE_DIR, {
    versions: VERSIONS_TF,
    variables: VARIABLES_TF,
    main: MAIN_TF,
    outputs: OUTPUTS_TF,
  });
}
