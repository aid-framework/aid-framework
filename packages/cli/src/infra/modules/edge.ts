/**
 * Provider code: the OpenTofu module an `edge` deployment is rendered into.
 *
 * The generator already emits the handler this module serves (`app.generated.edge`), so
 * the module's job is the AWS side: one Lambda@Edge function, versioned in us-east-1, and
 * one CloudFront distribution whose default behaviour answers every request from it.
 *
 * Lambda@Edge is not a smaller Lambda. It accepts no environment variables, no VPC, no
 * layers, no container images, no arm64 and no X-Ray, it caps a request at 30 seconds and
 * must be published as a numbered version in us-east-1. Those facts shape the module:
 *
 * * configuration travels in Secrets Manager, because it cannot travel in the function's
 *   environment; the module creates an empty secret named after the function, and the
 *   handler reads it by that name. Populate it out of band -- never in tfvars, which is
 *   state.
 * * `publish = true` is what CloudFront associates with; `$LATEST` and an alias are both
 *   refused.
 * * the role trusts both `lambda.amazonaws.com` and `edgelambda.amazonaws.com`, because a
 *   replica assumes it in every region CloudFront runs the function in.
 * * the invocation permission is scoped to `distribution/*` in this account rather than to
 *   the distribution's ARN: permission -> distribution ARN -> permission would be a cycle,
 *   and CloudFront refuses to associate a function it cannot invoke.
 *
 * What it refuses: more than one `edge` deployment (one distribution serves the whole app,
 * and the handler already routes every HTTP pipeline), a `streaming` deployment, a timeout
 * over 30 seconds, a memory size outside Lambda@Edge's range, and a missing zip.
 *
 * The origin is a documentation domain on purpose. CloudFront requires an origin on every
 * cache behaviour even when a function returns the response, so nothing is ever fetched
 * from it.
 */

