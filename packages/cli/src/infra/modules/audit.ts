/**
 * Provider code: the audit destination a deployment pins.
 *
 * One module for the whole environment rather than a fragment in each compute module,
 * because an audit record is written by the environment and not by one deployment: the
 * same sink would otherwise be created once per `cloudrun`, `cloudrunjob` and
 * `agent-runtime` module that reads the tfvar. `profileGate` refuses a document whose
 * deployments disagree, so the plan hands this module exactly one destination.
 *
 * What it deliberately does not do:
 *
 * - **Own the destination's location.** The region arrives from the env root, which is the
 *   operator's input and not the spec's (design §12.2). A spec that pins a region has it
 *   validated against its cloud by `profileGate`; the module never reads the pin, so a
 *   spec that pins no region is not handed a baked one.
 * - **Name the archive bucket.** An S3 or GCS bucket name is globally unique across every
 *   account on the planet, so nothing derivable from a project's name can be guaranteed
 *   free. `audit_bucket_name` is an operator input, like `image_uris` and `secret_arns`,
 *   and a precondition refuses an empty one rather than inventing a name that fails at
 *   apply. A CloudWatch log group name needs no such input: it is unique per account and
 *   region, which the derived name already satisfies.
 * - **Write the record.** It creates the destination and exports its id. The runtime and
 *   the provider's own log routing write to it.
 * - **Choose a retention policy.** Omitted retention means the sink's own default, which
 *   is the honest answer: AID does not invent a retention rule for an operator's log
 *   store. When the document does name one, every sink honours it -- a CloudWatch log
 *   group via `retention_in_days`, an archive bucket via a lifecycle expiration, and a
 *   BigQuery dataset via a partition expiration.
 */

