/**
 * The module, or nothing.
 *
 * Nothing is emitted when the document pins no audit destination, which keeps every
 * project that never named one byte-identical to the tree it generated before `audit`
 * existed -- including the README, which embeds the env root this module is called from.
 */
export function emitAuditModule(plan: DeployPlan, cloud: Cloud = DEFAULT_CLOUD): ModuleFile[] {
  if (plan.audit === undefined) return [];
  return cloud === 'gcp'
    ? moduleFiles(AUDIT_MODULE_DIR, {
        versions: GCP_VERSIONS_TF,
        variables: GCP_VARIABLES_TF,
        main: GCP_MAIN_TF,
        outputs: GCP_OUTPUTS_TF,
      })
    : moduleFiles(AUDIT_MODULE_DIR, {
        versions: AWS_VERSIONS_TF,
        variables: AWS_VARIABLES_TF,
        main: AWS_MAIN_TF,
        outputs: AWS_OUTPUTS_TF,
      });
}
