  '  labels = var.tags',
  '}',
  '',
  'resource "google_logging_project_sink" "audit_bigquery" {',
  '  count = var.audit.sink == "bigquery" ? 1 : 0',
  '',
  '  name                   = "aid-@{var.project.name}-audit"',
  '  project                = var.project_id',
