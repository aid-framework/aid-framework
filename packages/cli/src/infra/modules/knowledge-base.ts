/**
 * The module, or nothing.
 *
 * Nothing is emitted when the plan declares no Bedrock knowledge base, so a project
 * without one is handed no variables it would never set -- which is what keeps every
 * module's bytes constant and `tofu validate` meaningful for every project.
 */
export function emitKnowledgeBaseModule(plan: DeployPlan): ModuleFile[] {
  if (!plan.knowledgeBases.some((base) => base.engine === 'aws-bedrock')) return [];
  return moduleFiles(KNOWLEDGE_BASE_MODULE_DIR, {
    versions: VERSIONS_TF,
    variables: VARIABLES_TF,
    main: MAIN_TF,
    outputs: OUTPUTS_TF,
  });
}

/**
 * The input every AWS compute module declares so it can read a managed base.
 *
 * One variable rather than three (metadata, ids, ARNs) because the env root already
 * merges the created id and ARN into the plan's entry: a module that took them apart
 * would have to re-join them the same way, three times, in HCL.
 */
export const KNOWLEDGE_BASE_VARIABLES = [
  '',
  'variable "knowledge_bases" {',
  '  description = "Managed bases this module may read, with the id and ARN the env root resolved."',
  '  type = map(object({',
  '    # Empty until the base exists. The grant and the environment skip it while it is.',
  '    id  = optional(string, "")',
  '    arn = optional(string, "")',
  '    # The name the runtime reads the id from. Computed by the CLI, not here: HCL has no',
  '    # regex-lower-case-UPPER pipeline that would match the Python spelling exactly.',
  '    env_name   = string',
  '    retrievers = list(string)',
  '  }))',
  '  default = {}',
  '}',
];

/**
 * The locals a compute module adds beside its own.
 *
 * `knowledge_base_arns` is separated out because a policy whose `Resource` is `[""]` is
 * invalid rather than merely empty -- the same reason the secrets policy gates on a
 * non-empty map instead of rendering an empty statement.
 */
export function knowledgeBaseLocals(servicesLocal: string): string[] {
  return [
    '',
    '  # Only the bases that exist. `tofu plan` before the first apply sees none, and',
    '  # emitting a policy with an empty resource would fail the plan rather than skip it.',
    '  knowledge_base_arns = [for base in values(var.knowledge_bases) : base.arn if base.arn != ""]',
    '',
    "  # Exported only to a service that binds one of the base's retrievers, and only once",
    '  # the base exists: the runtime raises a named error for a missing id, while an empty',
    '  # string would read as a created base with an empty corpus.',
    '  knowledge_base_env = {',
    `    for id, service in local.${servicesLocal} : id => {`,
    '      for base_id, base in var.knowledge_bases :',
    '      base.env_name => base.id',
    '      if base.id != "" && length(setintersection(toset(base.retrievers), toset(service.ingest))) > 0',
    '    }',
    '  }',
  ];
}

/**
 * The retrieve grant.
 *
 * `servicesLocal` selects the per-service spelling (`for_each`, one policy per compute
 * role); omitting it selects the single-role spelling the batch module needs, where every
 * job runs under one task role and a `for_each` would create the same policy N times.
 */
export function knowledgeBaseGrant(roleRef: string, servicesLocal?: string): string[] {
  const lifecycle =
    servicesLocal === undefined
      ? ['  count = length(local.knowledge_base_arns) > 0 ? 1 : 0', `  role  = ${roleRef}`]
      : [
          `  for_each = length(local.knowledge_base_arns) > 0 ? local.${servicesLocal} : {}`,
          `  role     = ${roleRef}`,
        ];
  return [
    '',
    '# Retrieve is the only call the app makes: generation stays in this project, where the',
    '# model gate, the guardrail stage and the cost ledger can see it.',
    'resource "aws_iam_role_policy" "knowledge_base" {',
    ...lifecycle,
    '  name = "@{substr(replace("@{var.project.namespace}-@{var.project.name}", "/[^A-Za-z0-9-_]/", "-"), 0, 40)}-kb-retrieve"',
    '',
    '  policy = jsonencode({',
    '    Version = "2012-10-17"',
    '    Statement = [{',
    '      Effect   = "Allow"',
    '      Action   = ["bedrock:Retrieve"]',
    '      Resource = local.knowledge_base_arns',
    '    }]',
    '  })',
    '}',
  ];
}
