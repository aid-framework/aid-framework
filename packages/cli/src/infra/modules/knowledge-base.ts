/**
 * Provider code: the OpenTofu module a managed knowledge base is rendered into.
 *
 * A managed base inverts ownership. Locally this project reads a source, chunks it,
 * embeds it and writes vectors; here the engine owns every step after the source, and
 * the module's job is to create the base, point it at the corpus and get out of the way.
 *
 * What it deliberately does not do:
 *
 * - **Ingest.** `aws_bedrockagent_knowledge_base` is created empty. The first ingestion
 *   job is minutes long and costs money per document, so running it inside `apply`
 *   would make a plan's duration depend on corpus size and hide a bill behind a refresh.
 *   The base is created, and the operator (or `aid doctor`) starts ingestion.
 * - **Embed with the app's role.** The engine embeds, so the base's own role owns the
 *   `bedrock:InvokeModel` grant and the app's role only reads the result. That is why a
 *   `knowledgeBases[].embedModel` alias never reaches `embedder_for`.
 * - **Drop a filter.** `filterable` is carried here because Bedrock matches a metadata
 *   filter against a sidecar file beside each object; without the sidecar a filter
 *   matches nothing and returns an empty corpus that reads as "no answer". The IR gate
 *   refuses filter expressions for this version, so nothing here pretends to apply one.
 *
 * `prevent_destroy` is on for the base and its collection. Re-ingesting a corpus costs
 * API calls and money, and an upstream rename should not destroy one as a side effect.
 */

