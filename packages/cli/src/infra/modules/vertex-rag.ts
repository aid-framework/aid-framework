/**
 * Provider code: the Vertex AI RAG Engine counterpart of `knowledge-base.ts`.
 *
 * The bargain is the same as Bedrock's -- the engine owns chunking, embedding and the
 * index, and this module creates the corpus, points it at the source and stops -- but
 * the GCP API is shaped differently in three ways that decide this file:
 *
 * - **The corpus is the index.** `google_vertex_ai_rag_corpus` with
 *   `vector_db_config { rag_managed_db { knn {} } }` is a self-contained store, so there
 *   is no separate collection resource and no OCU floor to size. Pointing at an existing
 *   Vertex Vector Search index would need that index *and* its endpoint, which the plan's
 *   single `vector_store.arn` cannot carry; `existing` therefore means an existing
 *   *corpus*, named by the same `arn` field.
 * - **Import is per object.** The provider has no prefix import: `gcs_source.uris` names
 *   one file per `google_vertex_ai_rag_file`. A `gs://bucket/prefix` source is turned
 *   into one resource per listed object, which is why the listing below exists and why a
 *   large corpus produces a large plan. Bedrock imports a prefix in one data source;
 *   there is no equivalent here.
 * - **Deletion is guarded by the API.** The corpus carries `deletion_policy = "PREVENT"`
 *   rather than the `prevent_destroy` meta-argument. Both are set: the policy survives an
 *   out-of-band destroy, the meta-argument stops a plan from proposing one.
 *
 * What it deliberately does not do:
 *
 * - **Ingest.** Creating a RagFile starts an asynchronous import. The module defines the
 *   import; it does not wait for a bill or hide one inside `apply`.
 * - **Chunk.** Vertex has exactly one chunker, fixed-length. `recursive` and `code` are
 *   refused below rather than approximated, because a chunking setting the module cannot
 *   make true is worse than a plan that says so.
 * - **Filter.** As on Bedrock, the IR gate refuses filter expressions for this version.
 *   `filterable` is still carried so the runtime's config and the tfvars read alike.
 */

