/**
 * The input every GCP compute module declares so it can read a managed corpus.
 *
 * One variable rather than three, for the same reason as the AWS counterpart: the env
 * root already merged the created corpus name into the plan's entry, and a module that
 * took it apart would have to re-join it the same way, in HCL.
 */
export const VERTEX_KNOWLEDGE_BASE_VARIABLES = [
  '',
  'variable "knowledge_bases" {',
  '  description = "Managed corpora this module may read, with the corpus name the env root resolved."',
  '  type = map(object({',
  '    # Empty until the corpus exists. The environment skips it while it is.',
  '    id  = optional(string, "")',
  '    arn = optional(string, "")',
  '    # The name the runtime reads the corpus from. Computed by the CLI, not here: HCL has',
  '    # no regex-lower-case-UPPER pipeline that would match the Python spelling exactly.',
  '    env_name   = string',
  '    retrievers = list(string)',
  '  }))',
  '  default = {}',
  '}',
];

/**
 * The locals a GCP compute module adds beside its own.
 *
 * `knowledge_base_services` exists so `local.vertex` can include a service that reads a
 * corpus without any `google` model: `roles/aiplatform.user` is the role `:retrieveContexts`
 * needs, and it is the same role a Vertex model call needs, so one grant covers both.
 */
export function vertexKnowledgeBaseLocals(servicesLocal: string): string[] {
  return [
    '',
    '  # A service that binds a corpus. Keyed separately so `local.vertex` can union it',
    '  # with the services that name `google` as a model provider.',
    '  knowledge_base_services = {',
    `    for id, service in local.${servicesLocal} : id => service`,
    '    if length([',
    '      for base_id, base in var.knowledge_bases : base',
    '      if base.id != "" && length(setintersection(toset(base.retrievers), toset(service.ingest))) > 0',
    '    ]) > 0',
    '  }',
    '',
    "  # Exported only to a service that binds one of the base's retrievers, and only once",
    '  # the corpus exists: the runtime raises a named error for a missing id, while an empty',
    '  # string would read as a corpus with no documents.',
    '  knowledge_base_env = {',
    `    for id, service in local.${servicesLocal} : id => {`,
    '      for base_id, base in var.knowledge_bases :',
    '      base.env_name => base.id',
    '      if base.id != "" && length(setintersection(toset(base.retrievers), toset(service.ingest))) > 0',
    '    }',
    '  }',
  ];
}

/**
 * The module, or nothing.
 *
 * Nothing is emitted when the plan declares no Vertex corpus, so a project without one is
 * handed no variables it would never set -- which is what keeps every module's bytes
 * constant and `tofu validate` meaningful for every project.
 */
export function emitVertexRagModule(plan: DeployPlan): ModuleFile[] {
  if (!plan.knowledgeBases.some((base) => base.engine === 'vertex-rag')) return [];
  return moduleFiles(VERTEX_RAG_MODULE_DIR, {
    versions: VERSIONS_TF,
    variables: VARIABLES_TF,
    main: MAIN_TF,
    outputs: OUTPUTS_TF,
  });
}
