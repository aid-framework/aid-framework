/**
 * The module, or nothing: a plan whose services all run on compute the modules already
 * cover gains no directory and no manifest entry for a runtime it does not use.
 *
 * `cloud` selects the provider half. The command has already refused a service whose
 * platform does not run on this cloud, so this is a rendering choice and not a guess.
 */
export function emitAgentRuntimeModule(
  plan: DeployPlan,
  cloud: 'aws' | 'gcp' = 'aws',
): ModuleFile[] {
  const runtimes = plan.services.filter((service) => service.runtime !== undefined);
  if (runtimes.length === 0) return [];

  return moduleFiles(AGENT_RUNTIME_MODULE_DIR, {
    versions: cloud === 'aws' ? AWS_VERSIONS_TF : GCP_VERSIONS_TF,
    variables: cloud === 'aws' ? AWS_VARIABLES_TF : GCP_VARIABLES_TF,
    main: cloud === 'aws' ? AWS_MAIN_TF : GCP_MAIN_TF,
    outputs: cloud === 'aws' ? AWS_OUTPUTS_TF : GCP_OUTPUTS_TF,
  });
}
