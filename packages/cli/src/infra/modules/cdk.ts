/**
 * Provider code: the AWS CDK construct a `serverless` deployment is added to.
 *
 * The same argument that allows `serverless.ts` to carry HCL applies here: the construct
 * holds no fact the plan does not already state, because it loops over the context
 * document at synth time, so its bytes are a constant. `cdk synth` can therefore run once
 * in CI and be right for every project -- a stack that baked in per-service blocks would
 * be unverified again, one project at a time.
 *
 * It reads `deploy.cdk-context.json`, the same document the HCL module reads, so the two
 * backends cannot disagree about what a service is. Business inputs stay inputs: the image
 * each service runs, the ARN of each secret, and per-service sizing arrive in the app's
 * `inputs`, never in this file.
 *
 * What it provisions: one role per service, one container-image Lambda per service, and
 * one HTTP API with a `$default` stage routing each pipeline's endpoints. What it refuses,
 * with the same sentence the HCL module puts in a `precondition`: a `streaming` service, a
 * service with no image, and a secret with no ARN.
 */

import type { DeployPlan } from '@aid-framework/ir';

import type { Cloud } from '../cloud.js';
import { INFRA_GENERATED_DIR } from '../paths.js';
import { type ModuleFile, targets } from './hcl.js';

export const CDK_DIR = `${INFRA_GENERATED_DIR}/cdk`;
/** `.cjs`, because a generated project may be `"type": "module"` and CDK constructs are CJS. */
export const CDK_SERVERLESS_MODULE = `${CDK_DIR}/serverless.cjs`;

const SERVERLESS_JS = `'use strict';

/**
 * Generated by \`aid infra gen\`. Do not edit: the next run refuses to overwrite a
 * hand-edited file, and the construct carries no project-specific fact to keep.
 *
 * The AWS CDK spelling of \`infra/generated/modules/serverless\`: one container-image Lambda
 * per \`serverless\` service and one HTTP API routing each pipeline endpoint at its service.
 * It reads the same context document the module reads, so the two backends cannot drift.
 *
 * Business inputs stay inputs: the image each service runs, the ARN of each secret, and
 * per-service sizing arrive in \`inputs\`, never in the generated tree.
 */

const cdk = require('aws-cdk-lib');
const apigwv2 = require('aws-cdk-lib/aws-apigatewayv2');
const iam = require('aws-cdk-lib/aws-iam');
const lambda = require('aws-cdk-lib/aws-lambda');

/** Lambda names allow letters, digits, hyphens and underscores; a namespace may carry a dot. */
function nameOf(project, id) {
  return (project.namespace + '-' + project.name + '-' + id)
    .replace(/[^A-Za-z0-9-_]/g, '-')
    .slice(0, 64);
}

/**
 * Add every \`serverless\` service in \`context\` to \`scope\`.
 *
 * A refusal throws with the same sentence the OpenTofu module puts in a precondition, so
 * \`cdk synth\` fails for the reason \`tofu plan\` would: streaming cannot be delivered by an
 * HTTP API, a service needs an image, and a declared secret needs its ARN.
 */
function addServerless(scope, context, inputs) {
  const functions = {};
  const routed = [];
  const secretArns = inputs.secretArns || {};

  for (const id of Object.keys(context.services)) {
    const service = context.services[id];
    if (service.target !== 'serverless') continue;

    if (service.streaming) {
      throw new Error(
        'Service "' + id + '" declares streaming, which an HTTP API cannot deliver on AWS. ' +
          'Serve it from a container target here, or deploy it as serverless on GCP, where ' +
          'Cloud Run streams.',
      );
    }

    const image = (inputs.images || {})[id];
    if (!image) {
      throw new Error(
        'No images entry for "' + id + '". Name the container image this service runs; ' +
          'deployments[].image is a ghcr.io registry, which Lambda cannot pull from.',
      );
    }

    for (const variable of service.env) {
      if (variable.secret && !secretArns[variable.name]) {
        throw new Error(
          'Service "' + id + '" references a secret with no secretArns entry. ' +
            'Add name -> ARN for every secret it declares.',
        );
      }
    }

    const role = new iam.Role(scope, id + 'Role', {
      roleName: nameOf(context.project, id) + '-role',
      assumedBy: new iam.ServicePrincipal('lambda.amazonaws.com'),
      managedPolicies: [
        iam.ManagedPolicy.fromAwsManagedPolicyName('service-role/AWSLambdaBasicExecutionRole'),
      ],
    });

    const declaredSecrets = service.env.filter((variable) => variable.secret);
    if (declaredSecrets.length > 0 && Object.keys(secretArns).length > 0) {
      role.addToPolicy(
        new iam.PolicyStatement({
          actions: ['secretsmanager:GetSecretValue'],
          resources: Object.keys(secretArns).map((name) => secretArns[name]),
        }),
      );
    }

    const usesBedrock = (service.providers || []).includes('bedrock');
    if (usesBedrock) {
      role.addToPolicy(
        new iam.PolicyStatement({
          actions: ['bedrock:InvokeModel'].concat(
            service.streaming ? ['bedrock:InvokeModelWithResponseStream'] : [],
          ),
          resources: [
            'arn:' + cdk.Aws.PARTITION + ':bedrock:*::foundation-model/*',
            'arn:' +
              cdk.Aws.PARTITION +
              ':bedrock:*:' +
              cdk.Aws.ACCOUNT_ID +
              ':inference-profile/*',
          ],
        }),
      );
    }

    const variables = {};
    if (usesBedrock) variables.AWS_REGION = inputs.bedrockRegion || cdk.Aws.REGION;
    for (const variable of service.env) {
      if (variable.secret) {
        variables[variable.name] =
          '{{resolve:secretsmanager:' + secretArns[variable.name] + ':SecretString}}';
      } else if (variable.value !== undefined) {
        variables[variable.name] = variable.value;
      }
    }

    const sizing = (inputs.sizing || {})[id] || {};
    const tags = inputs.tags || {};
    const fn = new lambda.CfnFunction(scope, id + 'Function', {
      functionName: nameOf(context.project, id),
      role: role.roleArn,
      packageType: 'Image',
      code: { imageUri: image },
      memorySize: sizing.memoryMb || 1024,
      timeout: sizing.timeoutSeconds || 30,
      environment: { variables: variables },
      tags: Object.keys(tags).map((key) => ({ key: key, value: tags[key] })),
    });

    functions[id] = fn;
    routed.push({ id: id, service: service, fn: fn });
  }

  const withRoutes = routed.filter((entry) => entry.service.routes.length > 0);
  if (withRoutes.length === 0) return functions;

  const api = new apigwv2.CfnApi(scope, 'HttpApi', {
    name: context.project.namespace + '-' + context.project.name,
    protocolType: 'HTTP',
  });

  new apigwv2.CfnStage(scope, 'HttpApiDefaultStage', {
    apiId: api.ref,
    stageName: '$default',
    autoDeploy: true,
  });

  const integrations = {};
  for (const entry of routed) {
    integrations[entry.id] = new apigwv2.CfnIntegration(scope, entry.id + 'Integration', {
      apiId: api.ref,
      integrationType: 'AWS_PROXY',
      integrationUri:
        'arn:' +
        cdk.Aws.PARTITION +
        ':apigateway:' +
        cdk.Aws.REGION +
        ':lambda:path/2015-03-31/functions/' +
        entry.fn.attrArn +
        '/invocations',
      payloadFormatVersion: '2.0',
    });
  }

  for (const entry of withRoutes) {
    for (const route of entry.service.routes) {
      new apigwv2.CfnRoute(scope, entry.id + 'Route ' + route.method + ' ' + route.path, {
        apiId: api.ref,
        routeKey: route.method + ' ' + route.path,
        target: 'integrations/' + integrations[entry.id].ref,
      });
    }
  }

  for (const entry of withRoutes) {
    new lambda.CfnPermission(scope, entry.id + 'Invoke', {
      action: 'lambda:InvokeFunction',
      functionName: entry.fn.ref,
      principal: 'apigateway.amazonaws.com',
      sourceArn: api.attrExecuteApiArn + '/*/*',
      sourceAccount: cdk.Aws.ACCOUNT_ID,
    });
  }

  new cdk.CfnOutput(scope, 'ApiEndpoint', {
    description: 'The HTTP API base URL.',
    value:
      'https://' + api.ref + '.execute-api.' + cdk.Aws.REGION + '.' + cdk.Aws.URL_SUFFIX,
  });

  return functions;
}

module.exports = { addServerless: addServerless };
`;

/**
 * The construct, or nothing.
 *
 * Nothing is emitted on GCP, where no construct exists, and nothing for a plan with no
 * `serverless` service -- a container-only project gains no directory it cannot use.
 *
 * The literal above embeds this source file's line endings, so it is normalised here: a
 * checkout on another platform must not change the bytes `aid infra gen` writes.
 */
export function emitCdkModules(plan: DeployPlan, cloud: Cloud): ModuleFile[] {
  if (cloud !== 'aws') return [];
  if (!targets(plan, 'serverless')) return [];
  return [{ path: CDK_SERVERLESS_MODULE, contents: SERVERLESS_JS.replaceAll('\r\n', '\n') }];
}
