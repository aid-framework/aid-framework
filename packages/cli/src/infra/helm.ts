/**
 * The `helm` backend: a chart for the workloads a spec declares, rendered without touching
 * a cluster.
 *
 * What this backend is *not* is as important as what it is. The chart creates a Deployment,
 * a Service and, when the spec declares one, an Ingress. It creates no cluster, no
 * namespace, no Secret, no ConfigMap, no ingress controller and no registry entry. Every one
 * of those is a resource the customer's platform team already operates, and a generator that
 * quietly provisioned its own copy of any of them would be a second control plane -- which is
 * the one thing this framework does not have.
 *
 * The consequence is deliberate: `aid infra gen --iac helm` refuses a plan it cannot render
 * whole (`cli/infra-helm-surface-unsupported`) rather than emitting a chart that silently
 * omits a knowledge base or a managed guardrail the document asked for. A chart that
 * installs cleanly and then fails at run time is worse than a refusal that names the gap.
 */

import type { DeployEnvVar, DeployPlan, DeployService } from '@aid-framework/ir';

import { HELM_TARGETS } from './cloud.js';
import type { ModuleFile } from './modules/hcl.js';
import { INFRA_HELM_CHART_DIR } from './paths.js';

/** The chart's own version. The application's version is the image tag in `values.yaml`. */
const CHART_VERSION = '0.1.0';

const TEMPLATES_DIR = `${INFRA_HELM_CHART_DIR}/templates`;

/**
 * The header every emitted file starts with.
 *
 * A chart is read by operators who did not run the generator, so the first line says where
 * the file came from and what editing it costs. `aid infra gen --check` compares bytes, so a
 * hand edit is drift rather than a change.
 */
const HEADER = [
  '# Generated by AID from app/app.spec.yaml. Do not edit: `aid infra gen` overwrites it.',
  '# To change what this renders, change the spec; to own it, `aid eject` it.',
].join('\n');

/** Quote a string for YAML, always, so an id or host cannot change the document's shape. */
function quote(value: string): string {
  return `"${value.replaceAll('\\', '\\\\').replaceAll('"', '\\"')}"`;
}

/**
 * The DNS-1123 form of a deployment id, for object *names*.
 *
 * Spec ids are snake_case and Kubernetes object names are not, so `claims_prod` would be
 * rejected at admission. Label *values* keep the raw id, because `_` is legal there and the
 * point of the label is to match what the spec said.
 */
function dnsName(id: string): string {
  const lowered = id.toLowerCase().replaceAll('_', '-');
  let out = '';
  for (const character of lowered) {
    const code = character.charCodeAt(0);
    const allowed =
      (code >= 0x30 && code <= 0x39) || (code >= 0x61 && code <= 0x7a) || character === '-';
    if (allowed) out += character;
    else if (out !== '' && !out.endsWith('-')) out += '-';
  }
  return out.replace(/^-+|-+$/g, '') || 'app';
}

/** Code-unit ordering, never `localeCompare`, so emitted bytes are identical everywhere. */
function compareIds(a: string, b: string): number {
  if (a < b) return -1;
  if (a > b) return 1;
  return 0;
}

/** The services this backend renders, in canonical order. */
function workloadServices(plan: DeployPlan): DeployService[] {
  return plan.services
    .filter((service) => (HELM_TARGETS as readonly string[]).includes(service.target))
    .slice()
    .sort((left, right) => compareIds(left.id, right.id));
}

/**
 * The namespace the spec pinned, when it pinned exactly one.
 *
 * Used only for the install command in `NOTES.txt` and `README.md`. The templates render
 * into `.Release.Namespace`, so the operator's `--namespace` decides where a release lands;
 * printing the spec's value keeps the two from disagreeing silently.
 */
function declaredNamespace(services: readonly DeployService[]): string | undefined {
  const namespaces = new Set(
    services
      .map((service) => service.kubernetes?.namespace)
      .filter((namespace): namespace is string => namespace !== undefined),
  );
  return namespaces.size === 1 ? [...namespaces][0] : undefined;
}

/** A deployment id as a quoted Helm dictionary key. */
function valuesKey(id: string): string {
  return quote(id);
}

/**
 * One environment entry, as template lines.
 *
 * The three cases are the whole point of the plan's `secret` flag: a declared value is
 * literal, a secret is a reference into a Secret the operator creates, and anything else is
 * a reference into a ConfigMap. None of the three carries a value AID obtained itself.
 */
function envEntry(variable: DeployEnvVar): string[] {
  if (variable.secret) {
    return [
      `            - name: ${variable.name}`,
      '              valueFrom:',
      '                secretKeyRef:',
      '                  name: {{ dig "existingSecret" "aid-app-secrets" .Values }}',
      `                  key: ${variable.name}`,
    ];
  }
  if (variable.value !== undefined) {
    return [
      `            - name: ${variable.name}`,
      `              value: ${quote(variable.value)}`,
    ];
  }
  return [
    `            - name: ${variable.name}`,
    '              valueFrom:',
    '                configMapKeyRef:',
    '                  name: {{ dig "existingConfigMap" "aid-app-config" .Values }}',
    `                  key: ${variable.name}`,
    '                  optional: true',
  ];
}

/** The probes block, rendered only when the operator named a path. */
function probeBlock(service: DeployService): string[] {
  return [
    `          {{- with (dig "services" ${valuesKey(service.id)} "probes" "path" "" .Values) }}`,
    '          readinessProbe:',
    '            httpGet:',
    '              path: {{ . | quote }}',
    '              port: http',
    '            periodSeconds: 10',
    '          livenessProbe:',
    '            httpGet:',
    '              path: {{ . | quote }}',
    '              port: http',
    '            initialDelaySeconds: 15',
    '            periodSeconds: 20',
    '          {{- end }}',
  ];
}

/** The Deployment for one service. */
function deploymentTemplate(plan: DeployPlan, service: DeployService): string {
  const key = valuesKey(service.id);
  const name = dnsName(service.id);
  return [
    HEADER,
    'apiVersion: apps/v1',
    'kind: Deployment',
    'metadata:',
    `  name: {{ .Release.Name }}-${name}`,
    '  namespace: {{ .Release.Namespace }}',
    '  labels:',
    '    {{- include "aid-app.labels" . | nindent 4 }}',
    `    aid-framework/deployment: ${quote(service.id)}`,
    'spec:',
    `  replicas: {{ dig "services" ${key} "replicaCount" 2 .Values }}`,
    '  selector:',
    '    matchLabels:',
    '      {{- include "aid-app.selectorLabels" . | nindent 6 }}',
    '  template:',
    '    metadata:',
    '      labels:',
    '        {{- include "aid-app.selectorLabels" . | nindent 8 }}',
    `        aid-framework/deployment: ${quote(service.id)}`,
    '      annotations:',
    '        # Rolled on any change that reaches `values.yaml`, so a config-only edit is a new',
    '        # ReplicaSet rather than a running pod nobody restarted.',
    '        checksum/values: {{ include "aid-app.valuesChecksum" . }}',
    '    spec:',
    '      automountServiceAccountToken: false',
    '      securityContext:',
    '        runAsNonRoot: true',
    '        # The UID the generated Dockerfile creates for its `aid` user. A custom image',
    '        # must run as this UID, or a read-only root filesystem cannot be enforced.',
    '        runAsUser: {{ dig "podSecurity" "runAsUser" 10001 .Values }}',
    '        fsGroup: 10001',
    '        seccompProfile:',
    '          type: RuntimeDefault',
    '      containers:',
    '        - name: app',
    `          image: "{{ dig "image" "repository" ${quote(plan.project.name)} .Values }}:{{ dig "image" "tag" "latest" .Values }}"`,
    '          imagePullPolicy: {{ dig "image" "pullPolicy" "IfNotPresent" .Values }}',
    '          ports:',
    '            - name: http',
    `              containerPort: {{ dig "services" ${key} "port" 8080 .Values }}`,
    '              protocol: TCP',
    '          env:',
    '            - name: PORT',
    `              value: {{ dig "services" ${key} "port" 8080 .Values | quote }}`,
    ...service.env.flatMap(envEntry),
    '          securityContext:',
    '            allowPrivilegeEscalation: false',
    '            readOnlyRootFilesystem: {{ dig "podSecurity" "readOnlyRootFilesystem" false .Values }}',
    '            capabilities:',
    '              drop: ["ALL"]',
    '          resources:',
    `            {{- toYaml (dig "services" ${key} "resources" (dict "requests" (dict "cpu" "250m" "memory" "512Mi") "limits" (dict "cpu" "1" "memory" "1Gi")) .Values) | nindent 12 }}`,
    ...probeBlock(service),
    '          volumeMounts:',
    '            - name: tmp',
    '              mountPath: /tmp',
    '      volumes:',
    '        # A scratch directory that dies with the pod. It is what makes',
    '        # `readOnlyRootFilesystem: true` workable once the operator enables it.',
    '        - name: tmp',
    '          emptyDir: {}',
    '',
  ].join('\n');
}

/** The Service for one service. */
function serviceTemplate(service: DeployService): string {
  const name = dnsName(service.id);
  return [
    HEADER,
    'apiVersion: v1',
    'kind: Service',
    'metadata:',
    `  name: {{ .Release.Name }}-${name}`,
    '  namespace: {{ .Release.Namespace }}',
    '  labels:',
    '    {{- include "aid-app.labels" . | nindent 4 }}',
    'spec:',
    '  type: ClusterIP',
    '  selector:',
    '    {{- include "aid-app.selectorLabels" . | nindent 4 }}',
    `    aid-framework/deployment: ${quote(service.id)}`,
    '  ports:',
    '    - name: http',
    `      port: {{ dig "services" ${valuesKey(service.id)} "port" 8080 .Values }}`,
    '      targetPort: http',
    '      protocol: TCP',
    '',
  ].join('\n');
}

/** The Ingress for one service, or `undefined` when the spec declared no host. */
function ingressTemplate(service: DeployService): string | undefined {
  const ingress = service.kubernetes?.ingress;
  if (ingress === undefined) return undefined;
  const key = valuesKey(service.id);
  const name = dnsName(service.id);
  const host = `dig "services" ${key} "ingress" "host" ${quote(ingress.host)} .Values`;
  const className = `dig "services" ${key} "ingress" "className" ${quote(ingress.className)} .Values`;
  return [
    HEADER,
    'apiVersion: networking.k8s.io/v1',
    'kind: Ingress',
    'metadata:',
    `  name: {{ .Release.Name }}-${name}`,
    '  namespace: {{ .Release.Namespace }}',
    '  labels:',
    '    {{- include "aid-app.labels" . | nindent 4 }}',
    'spec:',
    `  ingressClassName: {{ ${className} }}`,
    ...(ingress.tlsSecret === undefined
      ? []
      : [
          '  tls:',
          "    # The certificate is the operator's: this depends on a Secret that exists rather",
          '    # than creating one, so a missing certificate fails loudly at admission instead of',
          '    # leaving a plaintext route that looks configured.',
          '    - hosts:',
          `        - {{ ${host} }}`,
          `      secretName: ${quote(ingress.tlsSecret)}`,
        ]),
    '  rules:',
    `    - host: {{ ${host} }}`,
    '      http:',
    '        paths:',
    '          - path: /',
    '            pathType: Prefix',
    '            backend:',
    '              service:',
    `                name: {{ .Release.Name }}-${name}`,
    '                port:',
    '                  name: http',
    '',
  ].join('\n');
}

/** `templates/_helpers.tpl`, which names the release once so every template agrees. */
function helpersTemplate(plan: DeployPlan): string {
  return [
    '{{/*',
    'Names the release and the values it rendered with. Generated by AID: the selector',
    'labels are what every Service matches on, so changing them re-creates every object.',
    '*/}}',
    '{{- define "aid-app.selectorLabels" -}}',
    'app.kubernetes.io/name: aid-app',
    'app.kubernetes.io/instance: {{ .Release.Name }}',
    '{{- end -}}',
    '',
    '{{- define "aid-app.labels" -}}',
    '{{ include "aid-app.selectorLabels" . }}',
    'app.kubernetes.io/managed-by: {{ .Release.Service }}',
    `app.kubernetes.io/part-of: ${quote(plan.project.name)}`,
    'helm.sh/chart: {{ printf "%s-%s" .Chart.Name .Chart.Version | replace "+" "_" }}',
    '{{- end -}}',
    '',
    '{{- define "aid-app.valuesChecksum" -}}',
    '{{ toYaml .Values | sha256sum }}',
    '{{- end -}}',
    '',
  ].join('\n');
}

/** `Chart.yaml`. */
function chartYaml(): string {
  return [
    HEADER,
    'apiVersion: v2',
    'name: aid-app',
    'description: >-',
    '  The workloads app/app.spec.yaml declares, rendered as Kubernetes objects. This chart',
    '  creates no cluster, namespace, Secret or ConfigMap: those belong to the platform that',
    '  installs it.',
    'type: application',
    `version: ${CHART_VERSION}`,
    '',
  ].join('\n');
}

/** `values.yaml`: the settings an operator reviews and may change. */
function valuesYaml(plan: DeployPlan, services: readonly DeployService[]): string {
  const lines = [
    HEADER,
    '#',
    '# One release installs every deployment the spec targets at `kubernetes`. The keys under',
    '# `services` are deployment ids, so an override names the deployment it changes.',
    '',
    'image:',
    `  repository: ${quote(plan.project.name)}`,
    '  tag: latest',
    '  pullPolicy: IfNotPresent',
    '',
    '# The Secret holding the values of the variables the spec marks `secret: true`. This',
    '# chart references keys in it and creates none -- AID never holds a secret value, and a',
    '# chart that templated one would put it in git. Create it before installing:',
    '#',
    '#   kubectl create secret generic aid-app-secrets \\',
    '#     --from-literal=OPENAI_API_KEY=... --namespace <namespace>',
    'existingSecret: aid-app-secrets',
    '',
    '# The ConfigMap holding non-secret variables the spec declares without a value. A missing',
    '# key is tolerated (`optional: true`) so the app starts and reports the gap itself,',
    '# rather than a pod that will not schedule.',
    'existingConfigMap: aid-app-config',
    '',
    '# What the pod is allowed to do. These are the settings a cluster with a Pod Security',
    '# Standard enforced actually cares about.',
    'podSecurity:',
    '  # The UID of the `aid` user the generated Dockerfile creates. Change it only to match',
    '  # an image you built yourself.',
    '  runAsUser: 10001',
    '  # Off by default. Turn it on when the app writes nothing outside /tmp: the root',
    '  # filesystem is the image, and a runtime that caches a model or a tokenizer to $HOME',
    '  # will fail at request time rather than at install. AID does not enable it on your',
    '  # behalf, because it has not run your app on a pod.',
    '  readOnlyRootFilesystem: false',
    '',
    'services:',
  ];
  for (const service of services) {
    const ingress = service.kubernetes?.ingress;
    lines.push(`  ${valuesKey(service.id)}:`);
    lines.push('    replicaCount: 2');
    lines.push('    port: 8080');
    lines.push('    resources:');
    lines.push('      requests:');
    lines.push('        cpu: 250m');
    lines.push('        memory: 512Mi');
    lines.push('      limits:');
    lines.push('        cpu: "1"');
    lines.push('        memory: 1Gi');
    lines.push('    probes:');
    lines.push('      # Empty means no probe is rendered. AID will not invent a health route the');
    lines.push('      # app does not serve: name one your `app/main.py` answers and the pod is');
    lines.push('      # restarted when it stops answering.');
    lines.push('      path: ""');
    if (ingress !== undefined) {
      lines.push('    ingress:');
      lines.push(`      host: ${quote(ingress.host)}`);
      lines.push(`      className: ${quote(ingress.className)}`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

/** `templates/NOTES.txt`, printed after an install. */
function notesTemplate(plan: DeployPlan, services: readonly DeployService[]): string {
  const namespace = declaredNamespace(services);
  const first = services[0];
  return [
    '{{/* Printed by `helm install` / `helm upgrade`. Generated by AID. */}}',
    'The release {{ .Release.Name }} is installed in namespace {{ .Release.Namespace }}.',
    '',
    'What this chart created:',
    ...services.map(
      (service) =>
        `  - {{ .Release.Name }}-${dnsName(service.id)} (Deployment, Service${
          service.kubernetes?.ingress === undefined ? '' : ', Ingress'
        })`,
    ),
    '',
    'What it did not create, and what it expects to find:',
    '  - the Secret {{ dig "existingSecret" "aid-app-secrets" .Values }}',
    '  - the ConfigMap {{ dig "existingConfigMap" "aid-app-config" .Values }}',
    `  - the image {{ dig "image" "repository" ${quote(plan.project.name)} .Values }}:{{ dig "image" "tag" "latest" .Values }}`,
    '  - the ingress controller each Ingress class names',
    '',
    'Check the rollout:',
    `  kubectl rollout status deployment/{{ .Release.Name }}-${dnsName(first?.id ?? 'app')} --namespace {{ .Release.Namespace }}`,
    '',
    ...(namespace === undefined
      ? []
      : [
          `The spec pins this workload to the namespace \`${namespace}\`, so install with`,
          `\`--namespace ${namespace}\` unless your platform places releases elsewhere.`,
          '',
        ]),
    'AID gates the document, not the cluster: it cannot see whether the Secret, the image or',
    'the ingress class exist. Those are properties of your platform, and this release reports',
    'them as declared rather than verified.',
    '',
  ].join('\n');
}

/** The chart's `README.md`, which is the operator's entry point. */
function chartReadme(plan: DeployPlan, services: readonly DeployService[]): string {
  const namespace = declaredNamespace(services) ?? 'default';
  const image = `${plan.project.name}:latest`;
  return [
    HEADER,
    '',
    '# The AID chart',
    '',
    'Rendered by `aid infra gen --iac helm` for the deployments in `app/app.spec.yaml` that',
    'target `kubernetes`. It describes what to run inside a cluster; it does not create the',
    'cluster, its namespace, its secrets or its ingress controller.',
    '',
    '## Workloads',
    '',
    '| Deployment | Namespace | Ingress |',
    '| --- | --- | --- |',
    ...services.map(
      (service) =>
        `| \`${service.id}\` | \`${service.kubernetes?.namespace ?? 'default'}\` | ${
          service.kubernetes?.ingress === undefined
            ? 'none'
            : `\`${service.kubernetes.ingress.host}\``
        } |`,
    ),
    '',
    '## Install',
    '',
    '```bash',
    "# The Secret the spec's `secrets:` name. This chart references it and creates none.",
    'kubectl create secret generic aid-app-secrets --from-literal=OPENAI_API_KEY=...',
    '',
    `helm upgrade --install ${plan.project.name} ${INFRA_HELM_CHART_DIR} \\`,
    `  --namespace ${namespace} --create-namespace`,
    '```',
    '',
    '## Before you install',
    '',
    `- **The image.** \`values.yaml\` defaults to \`${image}\`, which is what \`docker build\``,
    '  produces from `app/generated/Dockerfile`. Push it to your registry and set',
    '  `image.repository` and `image.tag`: `latest` in production is a rollback you cannot',
    '  name.',
    '- **The Secret and the ConfigMap.** Every variable the spec marks `secret: true` is a',
    '  `secretKeyRef` into `existingSecret`; every non-secret variable without a declared',
    '  value is a `configMapKeyRef` into `existingConfigMap`. Neither is created here.',
    '- **The probes.** `probes.path` is empty, so no probe is rendered. AID will not claim a',
    '  health route the generated app does not serve; set the path your `app/main.py` answers',
    '  and both probes use it.',
    '- **The pod security context.** `podSecurity.runAsUser` is the UID of the `aid` user the',
    '  generated Dockerfile creates, so it matches an image built from `app/generated/`.',
    '  `podSecurity.readOnlyRootFilesystem` is off; turn it on once you know the app writes',
    '  nothing outside `/tmp`. AID does not turn it on for you, because it has not run your',
    '  app on a pod.',
    '- **The ingress class.** `values.yaml` carries the class each Ingress names, so the',
    '  cluster must run that controller. A class the cluster does not have leaves the Ingress',
    '  `Accepted: False` rather than falling back to a default.',
    '',
    '## What is generated, and what is not',
    '',
    'Generated: `Chart.yaml`, `values.yaml`, every file under `templates/`, and this readme.',
    '`aid infra gen` overwrites all of them and `aid infra gen --check` fails when they drift.',
    'A change that belongs in the release goes in the spec; a change that belongs to your',
    'platform goes in the cluster.',
    '',
  ].join('\n');
}

/**
 * Every file the `helm` backend emits, in a stable order.
 *
 * The plan document is emitted alongside the chart by `emitInfra`, because `infra plan` reads
 * it and because it is the reviewable half of the diff: a chart change and a plan change
 * landing in one commit is what makes a release auditable without a hosted backend.
 */
export function emitHelmChart(plan: DeployPlan): ModuleFile[] {
  const services = workloadServices(plan);
  const files: ModuleFile[] = [
    { path: `${INFRA_HELM_CHART_DIR}/Chart.yaml`, contents: chartYaml() },
    { path: `${INFRA_HELM_CHART_DIR}/values.yaml`, contents: valuesYaml(plan, services) },
    { path: `${TEMPLATES_DIR}/_helpers.tpl`, contents: helpersTemplate(plan) },
  ];
  for (const service of services) {
    const name = dnsName(service.id);
    files.push({
      path: `${TEMPLATES_DIR}/${name}-deployment.yaml`,
      contents: deploymentTemplate(plan, service),
    });
    files.push({
      path: `${TEMPLATES_DIR}/${name}-service.yaml`,
      contents: serviceTemplate(service),
    });
    const ingress = ingressTemplate(service);
    if (ingress !== undefined) {
      files.push({ path: `${TEMPLATES_DIR}/${name}-ingress.yaml`, contents: ingress });
    }
  }
  files.push({ path: `${TEMPLATES_DIR}/NOTES.txt`, contents: notesTemplate(plan, services) });
  files.push({ path: `${INFRA_HELM_CHART_DIR}/README.md`, contents: chartReadme(plan, services) });
  return files;
}
