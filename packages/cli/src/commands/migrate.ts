/**
 * `aid migrate` — emit the SQL the declared stores need, for an operator to apply once.
 *
 * Both runtimes create their own schema on first connect (`CREATE ... IF NOT EXISTS`), so
 * this command is not how the application works; it is how the application is allowed to
 * *stop* creating schema. A production role that only needs `INSERT`/`SELECT` should not
 * hold `CREATE TABLE` because the first request happened to arrive before the table did.
 * Emitting the same schema as a reviewable file moves that one-time act to the operator
 * and leaves the application's `IF NOT EXISTS` as a no-op.
 *
 * Four decisions worth stating:
 *
 * - **Bootstrap only.** Every statement is idempotent, so re-applying is harmless. The file
 *   creates and never alters: once `aid_chunks` exists, `IF NOT EXISTS` skips the table,
 *   so an edited vector dimension would report success while the column kept its old type.
 *   A changed dimension is a *new* migration, and the header says so where the person
 *   editing the file will read it.
 * - **No target flag.** The SQL is identical for both runtimes -- they declare the same
 *   table, the same columns and the same operators -- so a `--target` option would imply a
 *   per-target difference that does not exist.
 * - **One file, whatever the store count.** The runtimes use a single shared `aid_chunks`
 *   table and do not key rows by store id, so a second `pgvector` store is not a second
 *   table. Emitting one file per store would print the same DDL twice and invite a reader
 *   to believe the stores are isolated.
 * - **The file is identified by its own header.** `migrations/` is a directory people keep
 *   their own migrations in. `aid migrate` only rewrites or deletes a file that carries the
 *   header it writes, so a hand-written `aid-schema.sql` is refused rather than replaced.
 *
 * The table DDL is restated here because neither runtime publishes it as a value the CLI
 * can import -- Python holds it in a module constant, TypeScript in another. That is a
 * third copy, so `migrate.test.ts` reads both runtimes' sources and fails when either one
 * stops agreeing with {@link AID_CHUNKS_TABLE}: the duplication is guarded rather than
 * hoped for.
 */

import { resolve, sep } from 'node:path';

import { createNodeSink } from '@aid-framework/generator-sdk';
import type { IndexMetric, IR, VectorStoreShape } from '@aid-framework/ir';
import { hasErrors } from '@aid-framework/spec';

import type { CliContext } from '../context.js';
import type { CliDiagnostic } from '../diagnostics.js';
import { CLI_DIAGNOSTIC_CODES, cliError, cliWarning } from '../diagnostics.js';
import { EXIT_FAILURE, EXIT_OK, EXIT_USAGE } from '../exit.js';
import type { CommandOutcome } from '../output.js';
import { outcome } from '../output.js';
import { lowerSpec, readSpec } from '../pipeline.js';
import { DEFAULT_SPEC_PATH } from '../targets.js';

export interface MigrateOptions {
  readonly spec: string | undefined;
  /** Directory for the migration file, repo-relative; defaults to `migrations`. */
  readonly out: string | undefined;
  /** Fail when the committed file does not match the spec; writes nothing. */
  readonly check: boolean;
  readonly dryRun: boolean;
}

/** The header that marks a file as this command's to rewrite. */
export const MIGRATION_MARKER = '-- Generated by aid migrate. Do not edit.';

const DEFAULT_OUT_DIR = 'migrations';
const FILE_NAME = 'aid-schema.sql';

/**
 * The table both runtimes declare, verbatim apart from the embedding type.
 *
 * `{embedding}` is replaced with `vector(N)` when the spec pins one dimension and with
 * `vector` when it does not. The column list, its types and its `NOT NULL`s are what the
 * runtimes' insert and select statements assume; a driver that added or renamed a column
 * would fail at runtime, not here.
 */
export const AID_CHUNKS_TABLE = `CREATE TABLE IF NOT EXISTS aid_chunks (
    chunk_id text PRIMARY KEY,
    doc_id text NOT NULL,
    uri text NOT NULL,
    chunk_index integer NOT NULL,
    start_offset integer NOT NULL,
    end_offset integer NOT NULL,
    body text NOT NULL,
    metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
    embedding {embedding} NOT NULL
);`;

const EXTENSION = 'CREATE EXTENSION IF NOT EXISTS vector;';

/** pgvector's operator classes, one per metric the IR models. */
const OPERATOR_CLASS: Record<IndexMetric, string> = {
  cosine: 'vector_cosine_ops',
  dot: 'vector_ip_ops',
  l2: 'vector_l2_ops',
};

/** Shared by both runtimes as the order in which a distance is written in a query. */
const METRIC_ORDER: readonly IndexMetric[] = ['cosine', 'dot', 'l2'];

interface IndexChoice {
  readonly name: string;
  readonly metric: IndexMetric;
}

interface SkippedStore {
  readonly id: string;
  readonly kind: string;
  readonly reason: string;
}

interface Plan {
  readonly pgvector: readonly VectorStoreShape[];
  readonly skipped: readonly SkippedStore[];
  readonly dimension: number | undefined;
  readonly indexes: readonly IndexChoice[];
  readonly sql: string | undefined;
  readonly warnings: readonly CliDiagnostic[];
}

function skipReason(store: VectorStoreShape): string {
  switch (store.kind) {
    case 'memory':
      return 'in-process, so there is nothing to provision';
    case 'custom':
      return 'the runtime supplies it, so `aid migrate` cannot know its schema';
    default:
      return 'a managed service that owns its own schema';
  }
}

/**
 * The dimension to pin, or `undefined` to leave the column dimensionless.
 *
 * Pinning is strictly better when it is possible: the database then rejects a record of
 * the wrong width at insert time, instead of storing two incompatible vectors in one
 * table. It is not possible when two stores disagree, because they share the table --
 * so that case warns instead of silently picking one.
 */
function dimensionOf(
  stores: readonly VectorStoreShape[],
  specPath: string,
): { value: number | undefined; warnings: readonly CliDiagnostic[] } {
  const declared = [...new Set(stores.map((store) => store.dimensions))].filter(
    (value): value is number => value !== undefined,
  );
  if (declared.length === 0) return { value: undefined, warnings: [] };
  if (declared.length === 1) return { value: declared[0], warnings: [] };

  return {
    value: undefined,
    warnings: [
      cliWarning({
        code: CLI_DIAGNOSTIC_CODES.migrateDimensionAmbiguous,
        message: `The declared pgvector stores pin different dimensions (${declared.join(', ')}), so the shared \`aid_chunks\` table is left dimensionless.`,
        path: [specPath],
        hint: 'One table cannot hold two widths; declare one dimension, or give the stores separate tables by hand.',
      }),
    ],
  };
}

/**
 * One HNSW index per metric a `pgvector`-backed retriever searches with.
 *
 * The runtimes never create an index -- a scan over `aid_chunks` is exact, which is fine
 * for a fixture corpus and quadratic for a real one -- so this is the one part of the file
 * that is a performance decision rather than a correctness one. HNSW is chosen because it
 * is the index pgvector ships that needs no training step; `ivfflat` would need data
 * before it could be built, which is the wrong shape for a first migration.
 */
function indexesFor(ir: IR): readonly IndexChoice[] {
  const pgvectorIds = new Set(
    ir.stores.filter((store) => store.kind === 'pgvector').map((store) => store.id),
  );
  const metrics = new Set<IndexMetric>();
  for (const retriever of ir.retrievers) {
    if (pgvectorIds.has(retriever.store)) metrics.add(retriever.index.metric);
  }
  return METRIC_ORDER.filter((metric) => metrics.has(metric)).map((metric) => ({
    name: `aid_chunks_embedding_${metric}_idx`,
    metric,
  }));
}

function renderSql(dimension: number | undefined, indexes: readonly IndexChoice[]): string {
  const table = AID_CHUNKS_TABLE.replace(
    '{embedding}',
    dimension === undefined ? 'vector' : `vector(${dimension})`,
  );
  const statements = [EXTENSION, table];
  for (const index of indexes) {
    statements.push(
      `CREATE INDEX IF NOT EXISTS ${index.name}\n    ON aid_chunks USING hnsw (embedding ${OPERATOR_CLASS[index.metric]});`,
    );
  }

  const header = [
    MIGRATION_MARKER,
    '--',
    '-- The schema the declared vector stores need. Apply it once, with DDL rights; the',
    '-- application itself only needs DML. Every statement is idempotent, so applying this',
    '-- file again is a no-op.',
    '--',
    '-- This file creates, and never alters. Changing a vector dimension or a distance',
    '-- metric is a new migration, not an edit to this one: the table already exists, so',
    '-- `IF NOT EXISTS` would skip the statement and report success over the old column.',
  ];

  return `${[...header, '', ...statements].join('\n')}\n`;
}

function plan(ir: IR, specPath: string): Plan {
  const pgvector = ir.stores.filter((store) => store.kind === 'pgvector');
  const skipped = ir.stores
    .filter((store) => store.kind !== 'pgvector')
    .map((store) => ({ id: store.id, kind: store.kind, reason: skipReason(store) }));
  const dimension = dimensionOf(pgvector, specPath);
  const indexes = indexesFor(ir);

  return {
    pgvector,
    skipped,
    dimension: dimension.value,
    indexes,
    sql: pgvector.length === 0 ? undefined : renderSql(dimension.value, indexes),
    warnings: dimension.warnings,
  };
}

type Action = 'created' | 'updated' | 'unchanged' | 'removed' | 'none';

/** Whether `relative`, resolved against `cwd`, lands outside the project. */
function escapes(cwd: string, relative: string): boolean {
  const root = resolve(cwd);
  const target = resolve(root, relative);
  return target !== root && !target.startsWith(root.endsWith(sep) ? root : `${root}${sep}`);
}

function describe(plan: Plan): string[] {
  const text = [`stores: ${plan.pgvector.length + plan.skipped.length} declared`];
  for (const store of plan.pgvector) text.push(`  ${store.id} (pgvector)`);
  for (const store of plan.skipped) {
    text.push(`  ${store.id} (${store.kind}) -- ${store.reason}`);
  }
  if (plan.sql === undefined) {
    text.push('no pgvector store is declared, so there is no SQL to emit');
  } else {
    text.push(
      `dimension: ${plan.dimension === undefined ? 'not pinned' : `${plan.dimension} (pinned)`}`,
    );
    if (plan.indexes.length > 0) {
      text.push(
        `indexes: ${plan.indexes.map((index) => `${index.name} (${index.metric})`).join(', ')}`,
      );
    } else {
      text.push('indexes: none -- no pgvector-backed retriever declares a distance');
    }
  }
  return text;
}

export function migrate(context: CliContext, options: MigrateOptions): CommandOutcome {
  const command = 'migrate';
  const specPath = options.spec ?? DEFAULT_SPEC_PATH;
  const outDir = (options.out ?? DEFAULT_OUT_DIR).replace(/[\\/]+$/, '') || DEFAULT_OUT_DIR;
  const path = `${outDir}/${FILE_NAME}`;
  const fields = { spec: specPath, path, check: options.check, dryRun: options.dryRun };

  // The sink refuses an escaping path by throwing, which reads as an internal error. A
  // caller who typed an absolute path gets the same refusal, but as an invocation error
  // that names the flag.
  if (escapes(context.cwd, path)) {
    return outcome({
      command,
      exitCode: EXIT_USAGE,
      fields,
      diagnostics: [
        cliError({
          code: CLI_DIAGNOSTIC_CODES.migrateOutEscapes,
          message: `\`--out\` resolves to "${path}", which is outside the project.`,
          hint: 'Give a directory inside the project, such as `migrations`.',
        }),
      ],
    });
  }

  const read = readSpec(context, specPath);
  if (!read.ok) {
    return outcome({ command, exitCode: EXIT_FAILURE, fields, diagnostics: read.diagnostics });
  }

  const lowered = lowerSpec(read.text, specPath);
  if (!lowered.ok) {
    return outcome({ command, exitCode: EXIT_FAILURE, fields, diagnostics: lowered.diagnostics });
  }

  const sink = createNodeSink(context.cwd);
  const planned = plan(lowered.ir, specPath);
  const existing = sink.read(path);
  const owned = existing?.startsWith(MIGRATION_MARKER) === true;
  const diagnostics = [...planned.warnings];

  let action: Action;
  if (planned.sql === undefined) {
    action = owned ? 'removed' : 'none';
  } else if (existing === undefined) {
    action = 'created';
  } else if (owned) {
    action = existing === planned.sql ? 'unchanged' : 'updated';
  } else {
    // Someone else's file. Refusing is the whole safety property of this command: the
    // point of a migrations directory is that its contents are reviewed once and applied
    // in order, so silently replacing an entry would rewrite history a database already
    // recorded.
    diagnostics.push(
      cliError({
        code: CLI_DIAGNOSTIC_CODES.refusingToOverwrite,
        message: `"${path}" exists and was not written by \`aid migrate\`.`,
        path: [path],
        hint: 'Move it aside, or pass `--out` to write the generated schema somewhere else.',
      }),
    );
    action = 'none';
  }

  const pending = action === 'created' || action === 'updated' || action === 'removed';
  const failed = hasErrors(diagnostics);

  if (pending && !options.check && !options.dryRun) {
    // `remove` and `write` are the sink's, so the path-escape guard and the atomic rename
    // are the ones every generated file already goes through.
    if (planned.sql === undefined) sink.remove(path);
    else sink.write(path, planned.sql);
  }

  const text = describe(planned);
  text.push(`${path}: ${action}`);
  if (options.check && pending) {
    text.push('the migration does not match the spec; run `aid migrate` and commit the result:');
    text.push(`  ${path}`);
  }

  const verb =
    action === 'unchanged' || action === 'none'
      ? 'migrate: ok'
      : options.check || options.dryRun
        ? `migrate: would be ${action}`
        : `migrate: ${action}`;
  text.push(verb);

  return outcome({
    command,
    exitCode: failed || (options.check && pending) ? EXIT_FAILURE : EXIT_OK,
    diagnostics,
    text: text.join('\n'),
    fields: {
      ...fields,
      action,
      written: pending && !options.check && !options.dryRun,
      dimension: planned.dimension ?? null,
      indexes: planned.indexes,
      stores: [
        ...planned.pgvector.map((store) => ({ id: store.id, kind: store.kind, status: 'emitted' })),
        ...planned.skipped.map((store) => ({
          id: store.id,
          kind: store.kind,
          status: 'skipped',
          reason: store.reason,
        })),
      ],
    },
  });
}
