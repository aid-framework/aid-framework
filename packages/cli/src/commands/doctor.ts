/**
 * `aid doctor` — diagnose a project against the spec it was generated from.
 *
 * The design names four questions and this command asks those four: is the spec still
 * buildable, is the tree the one this generator would write today, did a hand edit leave
 * the tree inconsistent, and is the tree older than the generator being asked about it.
 * Nothing here is a new rule about a file: the spec judgement is `compile`, the tree
 * judgement is `planRegeneration`, and the manifest reading is `readManifest` -- the same
 * three calls `aid gen --dry-run` makes. Doctor differs from that command only in that it
 * keeps going when a check fails, so one run reports every fact a reader can act on
 * instead of the first one.
 *
 * It is read-only by construction rather than by promise: the code path that writes an app
 * is `regenerate`, and this module does not import it.
 *
 * Severity is where the judgement lives, and it is deliberate:
 *
 * - An error is something the tree cannot answer for: a spec that does not compile, a
 *   manifest that cannot be read, a generated or business file that is missing, or a
 *   generated file a human edited (which blocks regeneration silently otherwise).
 * - A warning is something the tree works around: it was produced by a different version
 *   of the generator or of the IR, its generated bytes are older than the spec, or it
 *   still holds files the plan no longer produces. `aid gen` repairs all three without
 *   discarding anything, so a run that only warns exits 0 on purpose.
 *
 * A project that has never been generated is reported as one error naming the manifest,
 * not as a hundred missing files. Listing every file of an app that does not exist yet
 * describes the generator's output rather than a problem with the project.
 */

import {
  createNodeSink,
  planRegeneration,
  type RegenerationReport,
} from '@aid-framework/generator-sdk';
import { countBySeverity, hasErrors, sortDiagnostics } from '@aid-framework/spec';

import type { CliContext } from '../context.js';
import type { CliDiagnostic } from '../diagnostics.js';
import { CLI_DIAGNOSTIC_CODES, cliError, cliWarning } from '../diagnostics.js';
import { EXIT_FAILURE, EXIT_OK, EXIT_USAGE } from '../exit.js';
import type { CommandOutcome } from '../output.js';
import { outcome } from '../output.js';
import type { CompileOutcome } from '../pipeline.js';
import { compile, readManifest, readSpec } from '../pipeline.js';
import type { Target } from '../targets.js';
import { resolveTarget, unknownTargetDiagnostic } from '../targets.js';

export interface DoctorOptions {
  readonly spec: string | undefined;
  readonly target: string | undefined;
}

/**
 * The plan's verdict on the tree, split by what a reader has to do about it.
 *
 * `created` in `RegenerationReport` is not enough on its own, because it merges the two
 * owners: a missing generated file is a tree that cannot run, while a missing business
 * file is scaffolding that does not exist yet. The report's `actions` carry the owner of
 * each create, so the split is read off the plan rather than re-derived here.
 */
interface TreeFacts {
  readonly generatedMissing: readonly string[];
  readonly businessMissing: readonly string[];
  readonly outdated: readonly string[];
  readonly drifted: readonly string[];
  readonly stale: readonly string[];
  readonly unchanged: readonly string[];
  readonly kept: readonly string[];
}

function readTree(report: RegenerationReport): TreeFacts {
  const generatedMissing: string[] = [];
  const businessMissing: string[] = [];

  for (const action of report.actions) {
    if (action.kind !== 'create') continue;
    if (action.owner === 'generated') generatedMissing.push(action.path);
    else businessMissing.push(action.path);
  }

  return {
    generatedMissing,
    businessMissing,
    outdated: report.updated,
    drifted: report.drifted.map((drift) => drift.path),
    stale: report.stale,
    unchanged: report.unchanged,
    kept: report.kept,
  };
}

function lines(label: string, paths: readonly string[]): string[] {
  if (paths.length === 0) return [];
  return [label, ...paths.map((path) => `  ${path}`)];
}

function count(entries: readonly string[], one: string, many: string): string {
  return `${entries.length} ${entries.length === 1 ? one : many}`;
}

function treeSummary(facts: TreeFacts): string {
  const parts: string[] = [];
  if (facts.generatedMissing.length > 0) {
    parts.push(count(facts.generatedMissing, 'generated file missing', 'generated files missing'));
  }
  if (facts.businessMissing.length > 0) {
    parts.push(count(facts.businessMissing, 'business file missing', 'business files missing'));
  }
  if (facts.outdated.length > 0) {
    parts.push(count(facts.outdated, 'file out of date', 'files out of date'));
  }
  if (facts.drifted.length > 0) {
    parts.push(count(facts.drifted, 'file hand-edited', 'files hand-edited'));
  }
  if (facts.stale.length > 0) {
    parts.push(count(facts.stale, 'file no longer generated', 'files no longer generated'));
  }
  if (parts.length > 0) return `tree: ${parts.join(', ')}`;

  return `tree: ${facts.unchanged.length + facts.kept.length} file(s) match the spec`;
}

/**
 * The facts the manifest knows that the plan cannot: who wrote the tree, and from what.
 *
 * The comparison is against `target.manifest.version` -- the version of the generator this
 * binary would run -- not against the CLI's own package version, because the CLI ships a
 * generator without republishing it. That is the same comparison `determinism.ts` defines.
 */
function provenanceDiagnostics(
  target: Target,
  generatedBy: { generator: string; generatorVersion: string; irVersion: string },
  currentIrVersion: string | undefined,
): CliDiagnostic[] {
  const diagnostics: CliDiagnostic[] = [];
  const path = [target.manifestPath];

  if (generatedBy.generator !== target.manifest.name) {
    diagnostics.push(
      cliError({
        code: CLI_DIAGNOSTIC_CODES.provenanceMismatch,
        message: `"${target.manifestPath}" was written by target \`${generatedBy.generator}\`, not \`${target.manifest.name}\`.`,
        path,
        hint: `The tree belongs to \`${generatedBy.generator}\`. Ask about that target, or generate this one into its own project.`,
      }),
    );
  }

  if (generatedBy.generatorVersion !== target.manifest.version) {
    diagnostics.push(
      cliWarning({
        code: CLI_DIAGNOSTIC_CODES.versionMismatch,
        message: `"${target.manifestPath}" was written by ${generatedBy.generator} ${generatedBy.generatorVersion}; this one is ${target.manifest.version}.`,
        path,
        hint: 'Run `aid gen` to regenerate the tree with the generator you are asking about.',
      }),
    );
  }

  if (currentIrVersion !== undefined && generatedBy.irVersion !== currentIrVersion) {
    diagnostics.push(
      cliWarning({
        code: CLI_DIAGNOSTIC_CODES.versionMismatch,
        message: `"${target.manifestPath}" was generated from IR ${generatedBy.irVersion}; this spec builds IR ${currentIrVersion}.`,
        path,
        hint: 'Run `aid gen` to regenerate the tree from the current IR.',
      }),
    );
  }

  return diagnostics;
}

export function doctor(context: CliContext, options: DoctorOptions): CommandOutcome {
  const command = 'doctor';
  const target = resolveTarget(options.target);
  if (target === undefined) {
    return outcome({
      command,
      exitCode: EXIT_USAGE,
      diagnostics: [unknownTargetDiagnostic(options.target ?? '')],
    });
  }

  const specPath = options.spec ?? target.specPath;
  const diagnostics: CliDiagnostic[] = [];

  const read = readSpec(context, specPath);

  let compiled: CompileOutcome | undefined;
  let specOk = false;
  let irVersion: string | undefined;
  let specCounts = countBySeverity([]);

  if (read.ok) {
    compiled = compile(read.text, specPath, target);
    diagnostics.push(...compiled.diagnostics);
    specCounts = countBySeverity(compiled.diagnostics);
    if (compiled.ok) {
      specOk = true;
      irVersion = compiled.ir.irVersion;
    }
  } else {
    diagnostics.push(...read.diagnostics);
    specCounts = countBySeverity(read.diagnostics);
  }

  const sink = createNodeSink(context.cwd);
  const manifestRead = readManifest(sink, target);
  const manifest = manifestRead.ok ? manifestRead.manifest : undefined;
  const manifestState = !manifestRead.ok
    ? 'unreadable'
    : manifest === undefined
      ? 'absent'
      : 'present';

  if (!manifestRead.ok) {
    diagnostics.push(...manifestRead.diagnostics);
  } else if (manifest === undefined) {
    diagnostics.push(
      cliError({
        code: CLI_DIAGNOSTIC_CODES.manifestMissing,
        message: `No manifest at "${target.manifestPath}": this target's tree has never been generated.`,
        path: [],
        hint: 'Run `aid gen` to write the app, then ask again.',
      }),
    );
  } else {
    diagnostics.push(
      ...provenanceDiagnostics(target, manifest.generatedBy, specOk ? irVersion : undefined),
    );
  }

  let facts: TreeFacts | undefined;
  if (compiled?.ok === true && manifest !== undefined) {
    const report = planRegeneration(compiled.plan, { sink, manifest });
    facts = readTree(report);
    // The SDK's own verdict on hand edits and on files the plan no longer produces.
    // Re-reported rather than re-derived: `generatedDrift` is the code the rest of the
    // toolchain already means by that name, and a second code would be a second answer.
    diagnostics.push(...report.diagnostics);

    if (facts.generatedMissing.length > 0) {
      diagnostics.push(
        cliError({
          code: CLI_DIAGNOSTIC_CODES.filesMissing,
          message: `${count(facts.generatedMissing, 'generated file is', 'generated files are')} missing from the tree.`,
          // `path` in a diagnostic is one document path, rendered joined; a set of files
          // is not that. The paths are in the summary text and in the report's `tree`.
          path: [],
          hint: 'Run `aid gen` to write them from the spec.',
        }),
      );
    }

    if (facts.businessMissing.length > 0) {
      diagnostics.push(
        cliError({
          code: CLI_DIAGNOSTIC_CODES.businessMissing,
          message: `${count(facts.businessMissing, 'business file is', 'business files are')} missing: the tree has no prompts or business logic where the spec declares one.`,
          path: [],
          hint: 'Run `aid gen` to scaffold them. Business files are created once and never overwritten.',
        }),
      );
    }

    if (facts.outdated.length > 0) {
      diagnostics.push(
        cliWarning({
          code: CLI_DIAGNOSTIC_CODES.filesOutdated,
          message: `${count(facts.outdated, 'generated file is', 'generated files are')} older than the spec: nobody edited them, so regenerating loses nothing.`,
          path: [],
          hint: 'Run `aid gen` to bring the tree up to date.',
        }),
      );
    }
  }

  const finalCounts = countBySeverity(diagnostics);
  const manifestLine =
    manifestState === 'absent'
      ? 'absent, the tree has never been generated'
      : manifestState === 'unreadable'
        ? `${target.manifestPath}, unreadable`
        : manifest === undefined
          ? target.manifestPath
          : `${target.manifestPath}, generated by ${manifest.generatedBy.generator} ${manifest.generatedBy.generatorVersion}, IR ${manifest.generatedBy.irVersion}`;

  const texts: string[] = [
    finalCounts.error === 0
      ? `${target.name}: ok (0 errors, ${finalCounts.warning} warnings)`
      : `${target.name}: ${finalCounts.error} error(s), ${finalCounts.warning} warning(s)`,
    specOk
      ? `spec: ok (${specCounts.error} errors, ${specCounts.warning} warnings)`
      : `spec: ${specCounts.error} error(s), ${specCounts.warning} warning(s)`,
    `manifest: ${manifestLine}`,
  ];

  if (facts !== undefined) {
    texts.push(treeSummary(facts));
    texts.push(...lines('missing generated files:', facts.generatedMissing));
    texts.push(...lines('missing business files:', facts.businessMissing));
    texts.push(...lines('out of date, regenerate:', facts.outdated));
    texts.push(...lines('hand-edited generated files:', facts.drifted));
    texts.push(...lines('no longer generated:', facts.stale));
  } else if (compiled?.ok !== true) {
    texts.push('tree: not checked, the spec did not compile');
  } else if (manifestState === 'absent') {
    texts.push('tree: not checked, there is no manifest to compare it with');
  } else {
    texts.push('tree: not checked, the manifest could not be read');
  }

  return outcome({
    command,
    exitCode: hasErrors(diagnostics) ? EXIT_FAILURE : EXIT_OK,
    fields: {
      target: target.name,
      spec: specPath,
      manifest: {
        path: target.manifestPath,
        state: manifestState,
        ...(manifest === undefined ? {} : { generatedBy: manifest.generatedBy }),
      },
      specOk,
      counts: finalCounts,
      ...(facts === undefined
        ? {}
        : {
            tree: {
              generatedMissing: facts.generatedMissing,
              businessMissing: facts.businessMissing,
              outdated: facts.outdated,
              drifted: facts.drifted,
              stale: facts.stale,
              unchanged: facts.unchanged.length,
              kept: facts.kept.length,
            },
          }),
    },
    diagnostics: sortDiagnostics(diagnostics),
    text: texts.join('\n'),
  });
}
