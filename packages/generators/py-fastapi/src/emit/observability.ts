/**
 * `app/generated/observability.py`: a machine-readable account of what was emitted.
 *
 * The generator makes two promises about a spec -- the target capabilities in its
 * manifest and the capabilities each model declares -- and both are smaller or larger
 * than what the runtime can express. Rather than let the difference live only in prose,
 * the emitted app carries the reconciled answer: what was promised, what was wired, and
 * what had no runtime name to land in.
 */

import type { IR } from '@aid/ir';

import {
  GENERATOR_NAME,
  GENERATOR_VERSION,
  PY_FASTAPI_MANIFEST,
  PY_FASTAPI_TARGET,
} from '../manifest.js';
import { capabilityReport, modelCapabilities, providerAdapter } from '../names.js';
import { INDENT, pythonStatement } from '../python.js';
import { assemble, HEADER, importFrom } from '../template.js';
import type { EmittedFile } from './file.js';
import { GENERATED_ROOT, generated } from './file.js';
import { pythonDoc } from './text.js';

export const OBSERVABILITY_PATH = `${GENERATED_ROOT}/observability.py`;

export function emitObservability(ir: IR): EmittedFile {
  const advertised: Record<string, string[]> = {};
  const unrepresentable: Record<string, string[]> = {};
  for (const model of ir.models) {
    const adapter = providerAdapter(model.provider);
    if (adapter === undefined) continue;
    const mapped = modelCapabilities(adapter, model.capabilities ?? []);
    advertised[model.id] = mapped.advertised;
    unrepresentable[model.id] = mapped.dropped;
  }

  const report = {
    capabilities: capabilityReport(PY_FASTAPI_MANIFEST.capabilities),
    emitsAgainst: PY_FASTAPI_MANIFEST.emitsAgainst,
    generator: { name: GENERATOR_NAME, version: GENERATOR_VERSION },
    irVersion: ir.irVersion,
    models: { advertised, unrepresentable },
    observability: { redact: ir.observability.redact, trace: ir.observability.trace },
    target: PY_FASTAPI_TARGET,
  };

  const body = [
    'def generated_capabilities() -> dict[str, Any]:',
    pythonDoc(
      'The generator identity, the reconciliation of every declared capability, and the ' +
        'target settings the emitted wiring honours.',
      INDENT,
    ),
    pythonStatement('return ', report, INDENT),
  ].join('\n');

  return generated(
    OBSERVABILITY_PATH,
    assemble([
      HEADER,
      pythonDoc(
        'Generated by the py-fastapi target: what this app declares, and where each ' +
          'declaration landed.',
      ),
      importFrom('typing', ['Any']),
      body,
    ]),
  );
}
